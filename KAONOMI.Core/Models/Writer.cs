using System;
using System.Collections.Generic;
using System.Diagnostics.Contracts;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace KAONOMI.Core.Models
{
    /// <summary>
    /// A writing of the chat (<c>/write</c>), one document of the <c>ghostwriter</c> index: its general information, its
    /// actors, its locations and its chapters (each with its text). Its id is the slug of its title, given at its
    /// creation and kept when the title changes; the server keeps its version (one more at each save) and its date of
    /// creation. Never erased (<see cref="ISoftDeletable"/>).
    /// </summary>
    public class GhostWriter : EntityBase, ISoftDeletable
    {
        /// <summary>Never erased: marked deleted instead (<see cref="ISoftDeletable"/>).</summary>
        public bool isDeleted { get; set; } = false;

        public string description { get; set; } = string.Empty;
        public string goals { get; set; } = string.Empty;
        public string audienceDescription { get; set; } = string.Empty;
        public string author { get; set; } = Environment.UserName;
        public string style { get; set; } = string.Empty;
        public List<Actor> actors { get; set; } = new List<Actor>();
        public List<Location> locations { get; set; } = new List<Location>();
        public List<Chapter> chapters { get; set; } = new List<Chapter>();
        /// <summary>The summary of the whole writing (generated by the model of the chat in the PUBLISH tab, then edited).</summary>
        public string summary { get; set; } = string.Empty;

        /// <summary>When the writing was created (<see cref="EntityBase.date"/> is the date of its last version).</summary>
        public DateTime? created { get; set; }
        /// <summary>The version of the writing: 1 at its creation, one more at each save.</summary>
        public int version { get; set; }

        /// <summary>The slug of a title, as for the pages of the wiki ("writing" when nothing is left).</summary>
        public static string Slug(string? text)
        {
            var slug = Wiki.Slug(text);
            return slug == "page" ? "writing" : slug;
        }

        /// <summary>
        /// The writing made ready to be saved: the title trimmed, the id the slug of the title for a new writing (an id
        /// given by the client is made a slug too), the chapters numbered in their order.
        /// </summary>
        public void Normalize()
        {
            title = (title ?? string.Empty).Trim();
            id = string.IsNullOrWhiteSpace(id) || Guid.TryParse(id, out _) ? Slug(title) : Slug(id);
            if (title.Length == 0)
                title = id;
            actors ??= new List<Actor>();
            locations ??= new List<Location>();
            chapters = (chapters ?? new List<Chapter>()).OrderBy(c => c.position).ToList();
            for (var i = 0; i < chapters.Count; i++)
                chapters[i].position = i + 1;
        }
    }


    public class  Chapter
    {
        public string title { get; set; } = string.Empty;
        public int position { get; set; } = 1;
        public string description { get; set; } = string.Empty;
        public string perceptionGoal { get; set; } = string.Empty;
        public string ambiance { get; set; } = string.Empty;
        public List<string> comments { get; set; } = new List<string>();
        /// <summary>The text of the chapter, written in the text area (a double-click on the chapter).</summary>
        public string text { get; set; } = string.Empty;
        /// <summary>The footnotes of the chapter: each one anchored on a piece of its text (a link note:&lt;number&gt;).</summary>
        public List<Footnote> footnotes { get; set; } = new List<Footnote>();
    }

    /// <summary>A footnote of a chapter: its number, the words it is anchored on, its text and its links.</summary>
    public class Footnote
    {
        public int number { get; set; } = 1;
        public string anchor { get; set; } = string.Empty;
        public string text { get; set; } = string.Empty;
        public List<FootnoteLink> links { get; set; } = new List<FootnoteLink>();
    }

    /// <summary>A link of a footnote: its title and its address.</summary>
    public class FootnoteLink
    {
        public string title { get; set; } = string.Empty;
        public string url { get; set; } = string.Empty;
    }

    public class  Location
    {
        public string name { get; set; } = string.Empty;
        public string description { get; set; } = string.Empty;
        public string geoLocation { get; set; } = string.Empty;
        public string history { get; set; } = string.Empty;
        public string culture { get; set; } = string.Empty;
        public string imageUrl { get; set; } = string.Empty;
        public string wikiUrl { get; set; } = string.Empty;
    }


    public class Actor
    {
        public string name { get; set; } = string.Empty;
        public string description { get; set; } = string.Empty;
        public string howHeSpeaks { get; set; } = string.Empty;
        public string howHeThinks { get; set; } = string.Empty;
        public string hisMotivation { get; set; } = string.Empty;
        public string hisGoal { get; set; } = string.Empty;
        public string hisSecret { get; set; } = string.Empty;
        public string hisWeakness { get; set; } = string.Empty;
        public string hisStrength { get; set; } = string.Empty;
        public int hisIQ { get; set; } = 100;
        public int hisEQ { get; set; } = 100;
        public bool isMainCharacter { get; set; } = false;
        public bool isAsperger { get; set; } = false;
        public bool isDyslexic { get; set; } = false;
        /// <summary>Disqualified (the DISQUALIFIED button of /write): the actor is kept, set aside.</summary>
        public bool disqualified { get; set; } = false;
        /// <summary>The picture of the actor (uploaded or generated with Fooocus), in Pictures/kaonomi/writer/&lt;title&gt;.</summary>
        public string imagePath { get; set; } = string.Empty;
    }




    /// <summary>
    /// An entry of the journal of a writing (/write): one per action that changes its text (a save, a chapter added or
    /// removed, a text generated, corrected, dictated, a footnote…). The journal only grows: an entry is never changed
    /// nor deleted (no update, no delete in the API), its id and its date given by the server.
    /// </summary>
    public class GhostWriterJournal : EntityBase
    {
        /// <summary>The id of the writing (the slug of its title).</summary>
        public string writingId { get; set; } = string.Empty;
        /// <summary>The title of the writing (the book) at the time of the action.</summary>
        public string writingTitle { get; set; } = string.Empty;
        /// <summary>The kind of action: save, autosave, chapter-added, rewrite, translation, summary, dictation…</summary>
        public string action { get; set; } = string.Empty;
        /// <summary>The chapter concerned (its position and title), empty for the writing as a whole.</summary>
        public string chapter { get; set; } = string.Empty;
        /// <summary>The text given to the action (the text before a correction, the prompt of a generation).</summary>
        public string originalText { get; set; } = string.Empty;
        /// <summary>The text generated (by the model, the dictation, Fooocus…).</summary>
        public string generatedText { get; set; } = string.Empty;
        /// <summary>The text corrected (the result of a correction, a rewrite, a translation).</summary>
        public string correctedText { get; set; } = string.Empty;
        /// <summary>The model of the chat used, when there is one.</summary>
        public string model { get; set; } = string.Empty;
        /// <summary>When the action was made in the chat (the date of the entry is the one of its arrival on the server).</summary>
        public DateTime? happened { get; set; }
    }
}
