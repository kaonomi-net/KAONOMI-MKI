using System;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using KAONOMI.Chat.Models;

namespace KAONOMI.Chat.Services;

/// <summary>
/// The AI tools of the rich text editor (the tape of <c>/work</c>, the journal): the evaluation, the translation, the
/// spelling correction and the rewriting of a selection, and the generation of code, by the LLM selected in the chat
/// (through Ollama); the generation of an image with Fooocus (through the Kaonomi server).
/// </summary>
public sealed class WritingAssistant(OllamaModelService? ollama, Func<string?>? model, KaonomiAssistantService? server,
    string picturesDirectory, string logCategory, string subject)
{
    /// <summary>Name of the model of the chat (the one selected, the default model at first).</summary>
    public string? CurrentModelName => model?.Invoke();

    /// <summary>True when the LLM can be asked (Ollama and a model are available).</summary>
    public bool CanAsk => ollama is not null && model is not null;

    /// <summary>True when images can be generated with Fooocus (through the Kaonomi server).</summary>
    public bool CanGenerateImages => server is not null;

    /// <summary>Folder of the images generated with Fooocus.</summary>
    public string PicturesDirectory { get; } = picturesDirectory;

    /// <summary>
    /// Evaluation of <paramref name="text"/> by the model of the chat: <paramref name="system"/> as the system prompt,
    /// <paramref name="prompt"/> followed by the text as the question. The answer is Markdown (LaTeX turned to Unicode).
    /// </summary>
    public async Task<string> EvaluateAsync(string text, string system, string prompt, CancellationToken cancellationToken)
    {
        if (ollama is null || model?.Invoke() is not { Length: > 0 } name)
            throw new InvalidOperationException("No model is available for the evaluation.");
        ActivityLog.Info(logCategory, $"Evaluation of {text.Length} chars of {subject} asked to {name}");
        var answer = await ollama.ChatAsync(name, system, $"{prompt}\n\nTexte :\n\"\"\"\n{text}\n\"\"\"", cancellationToken);
        ActivityLog.Info(logCategory, $"Evaluation received ({answer.Length} chars)");
        // The renderer does not draw LaTeX: the formulas the model still writes that way become Unicode text.
        return LatexText.Convert(answer).Trim();
    }

    /// <summary>
    /// An image generated by Fooocus for <paramref name="prompt"/> (through <c>POST /image/generate</c> of the Kaonomi
    /// server), of <paramref name="aspectRatio"/> (width*height) in <paramref name="performance"/>, saved in
    /// <see cref="PicturesDirectory"/> as fooocus-date-the-prompt.png; returns its path. Throws with the reason when no
    /// image comes back.
    /// </summary>
    public async Task<string> GenerateImageAsync(string prompt, string aspectRatio, string performance, CancellationToken cancellationToken)
    {
        if (server is null)
            throw new InvalidOperationException("No Kaonomi server: images cannot be generated.");
        var request = new ImageGenerationRequest { Prompt = prompt.Trim(), AspectRatio = aspectRatio, Performance = performance };
        ActivityLog.Info(logCategory, $"Image requested from Fooocus ({aspectRatio}, {performance}): {prompt}");
        var result = await server.GenerateImagesAsync(request, cancellationToken);
        if (result.Error is { } error)
            throw new System.Net.Http.HttpRequestException(error);
        if (result.Images.FirstOrDefault()?.Base64 is not { Length: > 0 } data)
            throw new System.Net.Http.HttpRequestException("Fooocus returned no image.");

        System.IO.Directory.CreateDirectory(PicturesDirectory);
        var slug = new string(prompt.ToLowerInvariant().Select(c => char.IsAsciiLetterOrDigit(c) ? c : '-').ToArray());
        slug = string.Join('-', slug.Split('-', StringSplitOptions.RemoveEmptyEntries).Take(6));
        var fileName = $"fooocus-{DateTime.Now:yyyyMMdd-HHmmss}-{(slug.Length > 0 ? slug : "image")}";
        var path = System.IO.Path.Combine(PicturesDirectory, fileName + ".png");
        for (var i = 2; System.IO.File.Exists(path); i++)
            path = System.IO.Path.Combine(PicturesDirectory, $"{fileName}-{i}.png");
        await System.IO.File.WriteAllBytesAsync(path, Convert.FromBase64String(data), cancellationToken);
        ActivityLog.Info(logCategory, $"Image generated in {result.Seconds:0.#} s (seed {result.Seed}): {path}");
        return path;
    }

    /// <summary>
    /// Code written by the model of the chat for <paramref name="prompt"/>, in <paramref name="language"/> ("auto": the
    /// language the request asks for, else the one the model finds best). Returns the language of the code (its Markdown
    /// fence) and the code.
    /// </summary>
    public async Task<(string Language, string Code)> GenerateCodeAsync(string prompt, string language, CancellationToken cancellationToken)
    {
        if (ollama is null || model?.Invoke() is not { Length: > 0 } name)
            throw new InvalidOperationException("No model is available to generate code.");
        var auto = string.IsNullOrWhiteSpace(language) || language is "auto";
        ActivityLog.Info(logCategory, $"Code ({(auto ? "language chosen by the model" : language)}) asked to {name}: {ActivityLog.Excerpt(prompt)}");
        var answer = await ollama.ChatAsync(name,
            "You are an expert programmer. Write the code the user asks for"
            + (auto ? ", in the language the request names, else in the language best suited to it" : $", in {language}")
            + ". Answer with exactly one Markdown fenced code block whose fence names the language (```python, ```csharp…), "
            + "with short comments in the code itself, and nothing before or after the block.",
            prompt, cancellationToken);
        var fence = System.Text.RegularExpressions.Regex.Match(answer, @"```(?<language>[A-Za-z0-9#+_.-]*)[^\n]*\n(?<code>.*?)\n?```",
            System.Text.RegularExpressions.RegexOptions.Singleline);
        var written = fence.Success ? fence.Groups["language"].Value : auto ? string.Empty : language;
        var code = (fence.Success ? fence.Groups["code"].Value : answer).Replace("\r\n", "\n").Trim('\n');
        if (string.IsNullOrWhiteSpace(written) && !auto)
            written = language;
        ActivityLog.Info(logCategory, $"Code generated ({written}, {code.Split('\n').Length} lines)");
        return (written, code);
    }

    /// <summary>
    /// The language of <paramref name="text"/> (its English name: French, English, German…), identified by the LLM of the
    /// chat before its spelling is corrected.
    /// </summary>
    public async Task<string> DetectLanguageAsync(string text, CancellationToken cancellationToken)
    {
        if (ollama is null || model?.Invoke() is not { Length: > 0 } name)
            throw new InvalidOperationException("No model is available to identify the language.");
        var sample = text.Length > 1500 ? text[..1500] : text;
        var answer = await ollama.ChatAsync(name,
            "Identify the language of the text given by the user. Answer with the English name of that language only, in "
            + "one word (French, English, German, Spanish, Italian, Dutch…): no sentence, no punctuation.",
            sample, cancellationToken);
        var language = System.Text.RegularExpressions.Regex.Match(answer, @"\p{L}[\p{L} -]*").Value.Trim();
        if (language.Length == 0)
            language = "the language of the text";
        ActivityLog.Info(logCategory, $"Language of the selection: {language}");
        return language;
    }

    /// <summary>The prompt of ✨ Rewrite for readability.</summary>
    public const string ReadabilityPrompt = "Optimise la lisibilité du texte";

    /// <summary>
    /// The selected text corrected (<paramref name="mode"/> <c>spelling</c>: its spelling, grammar and punctuation,
    /// nothing else) or rewritten (<c>readability</c>: <see cref="ReadabilityPrompt"/>) by the LLM of the chat, in its own
    /// language, the formulas, numbers and symbols kept.
    /// </summary>
    public async Task<string> RewriteAsync(string text, string mode, CancellationToken cancellationToken, string? language = null)
    {
        if (ollama is null || model?.Invoke() is not { Length: > 0 } name)
            throw new InvalidOperationException("No model is available for the rewriting.");
        // The spelling is checked in the language of the text, identified first (DetectLanguageAsync).
        var task = mode == "spelling"
            ? $"Check and correct the spelling of this text in this language: {language ?? "the language of the text"}. "
              + "Correct only the spelling, the grammar, the conjugation, the agreements and the punctuation; keep the meaning, "
              + "the style, the right words and the order of the sentences."
            : ReadabilityPrompt + " donné par l'utilisateur : des phrases plus claires et plus courtes, un vocabulaire simple et précis, "
              + "un enchaînement logique, sans rien perdre du sens ni des informations.";
        ActivityLog.Info(logCategory, $"{(mode == "spelling" ? "Spelling correction" : "Rewriting for readability")} of {text.Length} chars of {subject} asked to {name}");
        var answer = await ollama.ChatAsync(name,
            task + " Écris dans la langue du texte. Garde les formules mathématiques, les nombres, les unités, les symboles "
            + "et les retours à la ligne. Réponds uniquement avec le texte obtenu : pas de commentaire, pas de guillemets, "
            + "pas de Markdown, pas de LaTeX.",
            text, cancellationToken);
        var result = Unwrap(answer);
        ActivityLog.Info(logCategory, $"Rewriting received ({result.Length} chars)");
        return result;
    }

    /// <summary>
    /// Translation of <paramref name="text"/> into <paramref name="language"/> (English, German, Dutch) by the model of
    /// the chat: the formulas, numbers and line breaks are kept; only the translation is returned.
    /// </summary>
    public async Task<string> TranslateAsync(string text, string language, CancellationToken cancellationToken)
    {
        if (ollama is null || model?.Invoke() is not { Length: > 0 } name)
            throw new InvalidOperationException("No model is available for the translation.");
        ActivityLog.Info(logCategory, $"Translation of {text.Length} chars of {subject} into {language} asked to {name}");
        var answer = await ollama.ChatAsync(name,
            $"You are a professional translator. Translate the text given by the user into {language}. Keep the mathematical "
            + "formulas, numbers, units, symbols and line breaks exactly as they are (one line of the translation per line of "
            + "the text). Answer with the translation only: no comment, no quotes, no Markdown, no LaTeX.",
            text, cancellationToken);
        var translation = Unwrap(answer);
        ActivityLog.Info(logCategory, $"Translation into {language} received ({translation.Length} chars)");
        return translation;
    }

    /// <summary>An answer taken out of the code block or the quotes it may be wrapped in.</summary>
    private static string Unwrap(string answer)
    {
        var result = answer.Trim();
        if (result.StartsWith("```", StringComparison.Ordinal))
            result = System.Text.RegularExpressions.Regex.Replace(result, @"^```[^\n]*\n|\n?```$", string.Empty).Trim();
        if (result.Length > 1 && result[0] is '"' or '«' or '“' && result[^1] is '"' or '»' or '”')
            result = result[1..^1].Trim();
        return result;
    }
}
