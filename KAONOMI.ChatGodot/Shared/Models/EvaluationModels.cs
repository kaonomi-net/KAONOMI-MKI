using System;
using System.Text.Json.Serialization;

namespace KAONOMI.Chat.Models;

/// <summary>
/// User feedback on an answer, sent to <c>PUT /evaluation</c> (<c>Evaluation</c> on the server side).
/// </summary>
public sealed class EvaluationEntry
{
    [JsonPropertyName("appName")]
    public string? AppName { get; set; }

    /// <summary>The project the document is attached to (the id of a <c>Project</c>, chosen by its name in the header of the window), or null.</summary>
    [JsonPropertyName("projectId")]
    public string? ProjectId { get; set; }

    [JsonPropertyName("id")]
    /// <summary>Generated by the client so the document always has an id.</summary>
    public string Id { get; set; } = Guid.NewGuid().ToString();

    [JsonPropertyName("date")]
    public DateTimeOffset Date { get; set; } = DateTimeOffset.Now;

    [JsonPropertyName("machineName")]
    public string? MachineName { get; set; }

    [JsonPropertyName("userName")]
    public string? UserName { get; set; }

    [JsonPropertyName("comment")]
    /// <summary>Context of the answer (model, tokens, duration).</summary>
    public string? Comment { get; set; }

    [JsonPropertyName("prompt")]
    /// <summary>User message the answer replied to.</summary>
    public string Prompt { get; set; } = string.Empty;

    [JsonPropertyName("completion")]
    /// <summary>The evaluated answer.</summary>
    public string Completion { get; set; } = string.Empty;

    /// <summary>Why the user liked or disliked the answer (server field name kept as is).</summary>
    [JsonPropertyName("explaination")]
    public string? Explanation { get; set; }

    [JsonPropertyName("isNegativeFeedback")]
    /// <summary>True for a thumb down, false for a thumb up.</summary>
    public bool IsNegativeFeedback { get; set; }
}
