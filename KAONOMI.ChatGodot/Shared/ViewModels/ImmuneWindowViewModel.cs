    public static string HistoryName(string path)
    {
        var name = Path.GetFileNameWithoutExtension(path);
        return DateTime.TryParseExact(name.Replace("immune-system-", ""), "yyyyMMdd-HHmmss", null, System.Globalization.DateTimeStyles.None, out var date)
            ? $"Scan of {date:yyyy-MM-dd HH:mm:ss}"
            : name;
    }

    private void LoadHistory()
    {
        History.Clear();
        if (!Directory.Exists(ReportsDirectory))
            return;
        foreach (var file in Directory.EnumerateFiles(ReportsDirectory, "*.json").OrderByDescending(f => f, StringComparer.Ordinal))
            History.Add(file);
    }

    /// <summary>Reads a report and shows it.</summary>
    public bool Load(string path)
    {
        try
        {
            var report = JsonSerializer.Deserialize<ImmuneReport>(File.ReadAllText(path), ImmuneReport.Json) ?? throw new JsonException("Empty report");
            report.File = path;
            Report = report;
            SelectedHistory = path;
            Stage = ImmuneStage.Report;
            SetStatus($"{HistoryName(path)}: {report.AiImages.Count} AI image(s), {report.OfficeFiles.Count} Office file(s) with code · {path}");
            return true;
        }
        catch (Exception ex) when (ex is IOException or JsonException or UnauthorizedAccessException)
        {
            ActivityLog.Error("Immune", $"{path} could not be read", ex);
            SetStatus($"{path} could not be read: {ex.Message}", true);
            return false;
        }
    }

    private bool CanRun() => !IsRunning;

    [RelayCommand(CanExecute = nameof(CanRun))]
    private async Task RunAsync()
    {
        if (!Images && !Office && !Browsing)
        {
            SetStatus("Choose at least the AI images, the Office code or the browsing history", true);
            return;
        }
        if (Scope == ImmuneScope.Folder && !Directory.Exists(Folder))
        {
            SetStatus($"{Folder} is not a folder", true);
            return;
        }

        _cancelled = false;
        Feed.Clear();
        Files = Directories = ImagesInspected = OfficeInspected = AiImagesFound = OfficeWithCode = AiServicesFound = 0;
        Seconds = 0;
        CurrentFolder = "";
        Stage = ImmuneStage.Running;
        SetStatus("Preparing the scanner…");
        var shown = Stopwatch.StartNew();

        try
        {
            Phase = "Building the scanner";
            var dll = await BuildAsync();
            if (dll is null)
                return;
            if (_cancelled)
            {
                Stage = Report is null ? ImmuneStage.Idle : ImmuneStage.Report;
                SetStatus("Cancelled");
                return;
            }

            Directory.CreateDirectory(ReportsDirectory);
            var output = Path.Combine(ReportsDirectory, $"immune-system-{DateTime.Now:yyyyMMdd-HHmmss}.json");
            var args = new List<string> { dll };
            if (Scope == ImmuneScope.Machine)
                args.Add("--machine");
            else if (Scope == ImmuneScope.Folder)
                args.Add(Folder);
            if (!Images)
                args.Add("--office-only");
            if (!Office)
                args.Add("--images-only");
            if (IncludeAll)
                args.Add("--all");
            if (!Browsing)
                args.Add("--no-history");
            args.AddRange(["--out", output, "--progress"]);

            var start = ProcessWindowViewModel.Dotnet(Home, [.. args]);
            if (start is null)
            {
                Fail("dotnet was not found: install the .NET 8 SDK");
                return;
            }
            // CANCEL writes "cancel" on its input: the scanner stops and still writes its report.
            start.RedirectStandardInput = true;
            Phase = "Scanning";
            SetStatus($"Scanning {(Scope switch { ImmuneScope.Machine => "the whole machine", ImmuneScope.Folder => Folder, _ => "your home folder" })}… CANCEL stops it and keeps what was found");
            _process = Process.Start(start) ?? throw new InvalidOperationException("The scanner did not start");
            _scanning = true;
            var stdout = _process.StandardOutput.ReadToEndAsync();
            string? reportPath = null;
            var log = new List<string>();
            while (await _process.StandardError.ReadLineAsync() is { } line)
            {
                if (OnLine(line) is { } path)
                    reportPath = path;
                else if (!line.StartsWith('{'))
                    log.Add(line);
            }
            await _process.WaitForExitAsync();
            await stdout;
            _scanning = false;
            var code = _process.ExitCode;
            _process.Dispose();
            _process = null;

            Phase = "Report";
            if ((reportPath ?? (File.Exists(output) ? output : null)) is { } done)
            {
                // The cell stays a little: a home folder is read in a second or two.
                Phase = _cancelled ? "Scan stopped" : "Scan complete";
                SetStatus($"{Phase}: {AiImagesFound} AI image(s), {OfficeWithCode} Office file(s) with code");
                await Task.Delay(TimeSpan.FromMilliseconds(Math.Max(1500, MinimumShow - shown.ElapsedMilliseconds)));
                LoadHistory();
                Load(done);
                if (_cancelled)
                    SetStatus($"Stopped: the report holds what was found until then · {done}");
            }
            else
            {
                Fail(_cancelled ? "Cancelled" : $"The scanner stopped (code {code}) without a report: {string.Join(" ", log.TakeLast(3))}");
            }
        }
        catch (Exception ex) when (ex is IOException or InvalidOperationException or System.ComponentModel.Win32Exception)
        {
            ActivityLog.Error("Immune", "The scan failed", ex);
            Fail($"The scan failed: {ex.Message}");
        }
    }

    private void Fail(string message)
    {
        Stage = Report is null ? ImmuneStage.Idle : ImmuneStage.Report;
        SetStatus(message, true);
    }

    /// <summary>Reads one JSON line of the scanner; the path of the report when the line announces it.</summary>
    private string? OnLine(string line)
    {
        if (!line.StartsWith('{'))
            return null;
        try
        {
            using var doc = JsonDocument.Parse(line);
            var e = doc.RootElement;
            switch (e.GetProperty("event").GetString())
            {
                case "progress":
                    Files = e.GetProperty("files").GetInt64();
                    Directories = e.GetProperty("directories").GetInt64();
                    ImagesInspected = e.GetProperty("images").GetInt64();
                    OfficeInspected = e.GetProperty("office").GetInt64();
                    AiImagesFound = e.GetProperty("aiImages").GetInt64();
                    OfficeWithCode = e.GetProperty("officeWithCode").GetInt64();
                    CurrentFolder = e.GetProperty("folder").GetString() ?? "";
                    Seconds = e.GetProperty("seconds").GetDouble();
                    break;
                case "found":
                    var hit = new ImmuneHit(e.GetProperty("type").GetString() ?? "", e.GetProperty("path").GetString() ?? "",
                        e.GetProperty("label").GetString() ?? "", e.GetProperty("level").GetString() ?? "");
                    Feed.Insert(0, hit);
                    while (Feed.Count > 14)
                        Feed.RemoveAt(Feed.Count - 1);
                    if (hit.Type == "image")
                        AiImagesFound++;
                    else if (hit.Type == "history")
                        AiServicesFound++;
                    else
                        OfficeWithCode++;
                    Found?.Invoke(hit);
                    break;
                case "report":
                    return e.GetProperty("path").GetString();
            }
        }
        catch (Exception ex) when (ex is JsonException or KeyNotFoundException or InvalidOperationException)
        {
            // Not a line of the scanner.
        }
        return null;
    }

    /// <summary>Builds the scanner from its project into ~/kaonomi/immune-system/bin; the path of its dll.</summary>
    private async Task<string?> BuildAsync()
    {
        var dll = Path.Combine(BinDirectory, "KAONOMI.ImmuneSystem.dll");
        var project = Path.Combine(ProcessWindowViewModel.FindProjects(), "KAONOMI.ImmuneSystem", "KAONOMI.ImmuneSystem.csproj");
        if (!File.Exists(project))
        {
            if (File.Exists(dll))
                return dll;
            Fail($"KAONOMI.ImmuneSystem was not found ({project})");
            return null;
        }
        SetStatus("Building KAONOMI.ImmuneSystem (dotnet build, once)…");
        var start = ProcessWindowViewModel.Dotnet(Path.GetDirectoryName(project)!, "build", project, "-c", "Release", "-nologo", "-v", "q", "-o", BinDirectory);
        if (start is null)
        {
            Fail("dotnet was not found: install the .NET 8 SDK");
            return null;
        }
        Directory.CreateDirectory(BinDirectory);
        using var build = Process.Start(start)!;
        _process = build;
        var output = build.StandardOutput.ReadToEndAsync();
        var errors = build.StandardError.ReadToEndAsync();
        await build.WaitForExitAsync();
        _process = null;
        if (_cancelled)
            return dll;
        if (build.ExitCode != 0 || !File.Exists(dll))
        {
            var text = (await output + await errors).Split('\n').Where(l => l.Contains("error", StringComparison.OrdinalIgnoreCase)).Take(2);
            Fail($"KAONOMI.ImmuneSystem could not be built: {string.Join(" ", text)}");
            return null;
        }
        return dll;
    }

    private bool CanCancel() => IsRunning;

    /// <summary>Stops the scan: "cancel" on the input of the scanner, which still writes what it found (the build is killed).</summary>
    [RelayCommand(CanExecute = nameof(CanCancel))]
    private void Cancel()
    {
        _cancelled = true;
        if (_process is not { HasExited: false } process)
            return;
        try
        {
            if (_scanning)
            {
                process.StandardInput.WriteLine("cancel");
                process.StandardInput.Flush();
                SetStatus("Stopping: the report is being written…");
            }
            else
            {
                process.Kill(entireProcessTree: true);
            }
        }
        catch (Exception ex) when (ex is InvalidOperationException or IOException or System.ComponentModel.Win32Exception)
        {
            ActivityLog.Error("Immune", "The scan could not be stopped", ex);
        }
    }

    [RelayCommand]
    private void NewScan()
    {
        if (!IsRunning)
            Stage = ImmuneStage.Idle;
    }

    /// <summary>Deletes the report shown, and shows the previous one.</summary>
    [RelayCommand]
    private void DeleteReport()
    {
        if (Report is null || IsRunning)
            return;
        try
        {
            File.Delete(Report.File);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            SetStatus($"{Report.File} could not be deleted: {ex.Message}", true);
            return;
        }
        Report = null;
        LoadHistory();
        if (History.FirstOrDefault() is { } previous)
            Load(previous);
        else
        {
            Stage = ImmuneStage.Idle;
            SetStatus("Report deleted");
        }
    }

    private void SetStatus(string text, bool error = false)
    {
        Status = text;
        IsError = error;
    }

