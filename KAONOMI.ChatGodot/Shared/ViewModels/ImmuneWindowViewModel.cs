/// <summary>Where /immune looks: the home folder, the whole machine, or one folder.</summary>
public enum ImmuneScope { Home, Machine, Folder }

/// <summary>What the window shows: the start screen, the scan running, or a report.</summary>
public enum ImmuneStage { Idle, Running, Report }

/// <summary>A finding announced by the scanner while it runs (the live feed of the animation).</summary>
public sealed record ImmuneHit(string Type, string Path, string Label, string Level)
{
    public string Name => System.IO.Path.GetFileName(Path);
}

/// <summary>
/// /immune: runs KAONOMI.ImmuneSystem (the images generated by AI and the code in Office files on this machine) and
/// shows its JSON report. The scanner is built once with dotnet into ~/kaonomi/immune-system/bin, then run from there
/// with <c>--progress</c>: its JSON lines on the error output drive the animation, and CANCEL writes "cancel" on its input. The reports are kept in
/// ~/kaonomi/immune-system/reports.
/// </summary>
public partial class ImmuneWindowViewModel : ViewModelBase
{
    /// <summary>How long the animation is shown at least (ms).</summary>
    private const long MinimumShow = 4500;

    private Process? _process;
    private bool _scanning;
    private bool _cancelled;

    public ImmuneWindowViewModel()
    {
        LoadHistory();
        if (History.FirstOrDefault() is { } last)
            Load(last);
    }

    public static string Home => Path.Combine(ChatSettings.KaonomiHome, "immune-system");
    public static string ReportsDirectory => Path.Combine(Home, "reports");
    private static string BinDirectory => Path.Combine(Home, "bin");

