    /// <summary>The AI images by generator, most first (the small ones grouped in "Other").</summary>
    public static List<(string Label, int Count)> ByGenerator(ImmuneReport report, int max = 7)
    {
        var groups = report.AiImages.GroupBy(i => Short(i.Generator ?? "Unknown")).Select(g => (g.Key, g.Count())).OrderByDescending(g => g.Item2).ToList();
        if (groups.Count <= max)
            return groups;
        return [.. groups.Take(max - 1), ("Other", groups.Skip(max - 1).Sum(g => g.Item2))];
    }

    private static string Short(string generator)
    {
        var paren = generator.IndexOf(" (", StringComparison.Ordinal);
        return generator.StartsWith("Stable Diffusion", StringComparison.Ordinal) ? "Stable Diffusion"
            : generator.StartsWith("Google", StringComparison.Ordinal) ? "Google (Gemini / Imagen)"
            : paren > 0 && generator.Length > 28 ? generator[..paren] : generator;
    }

    public static readonly string[] Levels = ["high", "medium", "low"];
    public static readonly string[] Severities = ["high", "medium", "low", "info"];

    public static List<(string Label, int Count)> ByConfidence(ImmuneReport report) =>
        Levels.Select(l => (l, report.AiImages.Count(i => i.Confidence == l))).ToList();

    public static List<(string Label, int Count)> BySeverity(ImmuneReport report) =>
        Severities.Select(s => (s, report.OfficeFiles.Count(o => o.Severity == s))).ToList();

    /// <summary>The Office files by kind of finding (a file counts once per kind).</summary>
    public static List<(string Label, int Count)> ByKind(ImmuneReport report) =>
        report.OfficeFiles.SelectMany(o => o.Findings.Select(f => f.Kind).Distinct())
            .GroupBy(k => k).Select(g => (g.Key, g.Count())).OrderByDescending(g => g.Item2).ToList();

    /// <summary>The AI images by month of their file (the last 12 months that have some, oldest first).</summary>
    public static List<(string Label, int Count)> ByMonth(ImmuneReport report) =>
        report.AiImages.GroupBy(i => new DateTime(i.Modified.Year, i.Modified.Month, 1)).OrderBy(g => g.Key).TakeLast(12)
            .Select(g => (g.Key.ToString("MMM yy", System.Globalization.CultureInfo.InvariantCulture), g.Count())).ToList();

    public static readonly string[] Categories = ["chat", "image", "video", "audio", "code", "writing"];

    public static string CategoryName(string category) => category switch
    {
        "chat" => "Assistants",
        "image" => "Images",
        "video" => "Video",
        "audio" => "Music and voices",
        "code" => "Code",
        "writing" => "Writing",
        _ => category,
    };

    /// <summary>The visits to AI services by category.</summary>
    public static List<(string Label, long Count)> VisitsByCategory(ImmuneBrowsers browsers) =>
        Categories.Select(c => (c, browsers.AiServices.Where(s => s.Category == c).Sum(s => s.Visits))).Where(c => c.Item2 > 0).ToList();

    /// <summary>The visits to AI services per month and category (the last 12 months that have some, oldest first).</summary>
    public static List<(string Month, List<(string Category, long Count)> Parts)> VisitsByMonth(ImmuneBrowsers browsers) =>
        browsers.AiServices.SelectMany(s => s.Months.Select(m => (Month: m.Key, s.Category, Count: m.Value)))
            .GroupBy(x => x.Month).OrderBy(g => g.Key, StringComparer.Ordinal).TakeLast(12)
            .Select(g => (Label(g.Key), Categories.Select(c => (c, g.Where(x => x.Category == c).Sum(x => x.Count))).ToList())).ToList();

    private static string Label(string month) =>
        DateTime.TryParseExact(month, "yyyy-MM", System.Globalization.CultureInfo.InvariantCulture, System.Globalization.DateTimeStyles.None, out var d)
            ? d.ToString("MMM yy", System.Globalization.CultureInfo.InvariantCulture)
            : month;

    /// <summary>The folders holding the most AI images.</summary>
    public static List<(string Label, int Count)> ByFolder(ImmuneReport report, int max = 6)
    {
        var home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
        return report.AiImages.GroupBy(i => Path.GetDirectoryName(i.Path) ?? "").OrderByDescending(g => g.Count()).Take(max)
            .Select(g => (ShortFolder(g.Key.StartsWith(home, StringComparison.Ordinal) ? "~" + g.Key[home.Length..] : g.Key), g.Count())).ToList();
    }

    /// <summary>A long folder as its last two names (…/images/2026).</summary>
    private static string ShortFolder(string folder)
    {
        if (folder.Length <= 32)
            return folder;
        var parts = folder.Split(Path.DirectorySeparatorChar, StringSplitOptions.RemoveEmptyEntries);
        var tail = string.Join(Path.DirectorySeparatorChar, parts.TakeLast(2));
        return "…" + Path.DirectorySeparatorChar + (tail.Length > 30 ? "…" + tail[^29..] : tail);
    }
