/// <summary>
/// /work: the tape of the calculations as a rich document (port of CalculatorView of the Avalonia chat). Above, the
/// document caption and the status; then a ribbon in the manner of Word, fixed while the document scrolls, with three
/// tabs. Home: New (the document saved first, then the tape emptied), Save / Open (documents of the Kaonomi server),
/// Word, Export JSON, Import JSON, the font, size, B I U S, color and clear formatting of the selection, the alignment,
/// the paragraph style, ✨ AI review (waiting popup with Cancel), the calculator (its own window). Insert: pictures, a
/// picture generated with Fooocus, crop the selected picture, link, the graph (its own window), code, code generated by
/// the LLM. View: the zoom of the page (also Ctrl / ⌘ + wheel). Right click on the tape: correct the spelling (the
/// language identified first) and rewrite for readability (waiting popup), evaluate, translate, cut, copy, paste. A
/// double-click on a picture opens it in the image analysis window; pictures dropped from the Finder / Explorer are
/// copied into the pictures folder of the calculator and inserted.
/// </summary>
[ToolView(typeof(CalculatorViewModel), "Work", "🧮", 1180, 760)]
public sealed class WorkView : IToolView
{
    public Control Build(object viewModel, Shell shell) => new WorkPage((CalculatorViewModel)viewModel, shell).Root;
}

/// <summary>The controls and the actions of one window of /work.</summary>
internal sealed class WorkPage
{
    private readonly CalculatorViewModel _vm;
    private readonly Shell _shell;
    private readonly TapeEditor _editor;
    private readonly Overlay _overlay;
    private readonly Label _status;
    private readonly TapeRibbon _ribbon;
    private Button _review = null!, _new = null!;
    private Window? _dropWindow;

    public WorkPage(CalculatorViewModel vm, Shell shell)
    {
        _vm = vm;
        _shell = shell;
        _editor = new TapeEditor
        {
            Placeholder = "The calculations done with = are written here, and kept. Type your notes anywhere; select text to format it."
        };
        _overlay = new Overlay();
        _status = Eve.Eve.Text_("", Eve.Eve.Green, 11);
        Root = new MarginContainer { SizeFlagsHorizontal = Control.SizeFlags.ExpandFill, SizeFlagsVertical = Control.SizeFlags.ExpandFill };
        _ribbon = new TapeRibbon(_editor, _overlay, shell, Root, _status, vm, "Calculator", "the tape", "work", _ => _vm.GraphPicturesDirectory);

        // The tape, both ways.
        _editor.TextCommitted += text => _vm.Tape = text;
        Bind.When(_editor, vm, () => _editor.Text = vm.Tape, nameof(vm.Tape));
        _editor.LoadImage = async path => AvaloniaBridge.ToTexture(await vm.LoadTapeImageAsync(path));
        _editor.OpenImage = OpenImageAnalysis;

        // The document (its title, version and date) is the title of the window; the status goes at the right of the
        // tabs of the ribbon: nothing above the ribbon.
        Bind.When(Root, vm, UpdateTitle, nameof(vm.DocumentCaption));

        // The page: the ribbon fixed above, the document scrolling below.
        var scroll = Ui.Scroll(_editor);
        scroll.SizeFlagsVertical = Control.SizeFlags.ExpandFill;
        var page = new PanelContainer { SizeFlagsVertical = Control.SizeFlags.ExpandFill };
        page.AddThemeStyleboxOverride("panel", Eve.Eve.Box(WorkPalette.Page, Eve.Eve.Edge with { A = 0.45f }, 0));
        page.AddChild(Ui.Column(0, BuildRibbon(), scroll));

        var content = Ui.Margin(page, 8, 6, 8, 8);
        Root.AddChild(content);
        Root.AddChild(_overlay);

        Root.Ready += () => Callable.From(OnReady).CallDeferred();
        Bind.OnGone(Root, () =>
        {
            if (_dropWindow is { } window && GodotObject.IsInstanceValid(window))
                window.FilesDropped -= OnFilesDropped;
            _dropWindow = null;
        });
    }

    /// <summary>The content of the window.</summary>
    public MarginContainer Root { get; }

    /// <summary>The title of the window: Work, then the document (title, version, date) when there is one.</summary>
    private void UpdateTitle()
    {
        if (!GodotObject.IsInstanceValid(Root) || _shell.WindowOf(Root) is not { } window)
            return;
        // Without a document the caption is a sentence about the tape: the title stays Work.
        var caption = _vm.CurrentDocument is null ? string.Empty : _vm.DocumentCaption.Replace("📄", string.Empty).Trim();
        window.Title = caption.Length == 0 ? "Work" : $"Work · {caption}";
    }

    private void OnReady()
    {
        if (!GodotObject.IsInstanceValid(Root))
            return;
        if (_dropWindow is null)
        {
            _dropWindow = Root.GetTree().Root;
            _dropWindow.FilesDropped += OnFilesDropped;
        }
        UpdateTitle();
        // The calculator and the graph belong to this window: they close with it.
        if (_shell.WindowOf(Root) is { } window)
            window.Closed += () =>
            {
                if (_calculator is not null)
                    _shell.Close(_calculator);
                if (_graph is not null)
                    _shell.Close(_graph);
            };
        _editor.GrabFocus();
    }

    // ───────────── Ribbon ─────────────

    /// <summary>The ribbon of the tape: the groups of the editor (<see cref="TapeRibbon"/>) and the ones of /work.</summary>
    private Control BuildRibbon()
    {
        _new = TapeRibbon.BigTool("📄", "New", "New document: the document you were working on is saved first (a new version on the Kaonomi server), then the tape is emptied", OnNewDocument);
        var save = TapeRibbon.BigTool("💾", "Save", "Save the tape as a document on the Kaonomi server (a new version each time; the description is written by the LLM)");
        save.Pressed += () => ShowSaveFlyout(save);
        save.Visible = _vm.CanUseDocuments;
        var open = TapeRibbon.BigTool("📂", "Open", "Open a document: the 3 you worked on last, or search them (title, description, content)");
        open.Pressed += () => ShowLoadFlyout(open);
        open.Visible = _vm.CanUseDocuments;
        var document = TapeRibbon.Group("Document", false, _new, save, open);

        var word = TapeRibbon.BigTool("📄⬇", "Word", "Export the tape, with its pictures, to a Word document (.docx)", OnExportWord);
        var exportJson = TapeRibbon.BigTool("⬇", "Export JSON", "Export the tape to a JSON file, its pictures inside it (base 64): one file to send or keep", OnExportJson, Eve.Eve.Cyan);
        var importJson = TapeRibbon.BigTool("⬆", "Import JSON", "Import a tape exported in JSON: its pictures are written into the pictures folder of the calculator (Pictures/kaonomi/maths) and linked again", OnImportJson, Eve.Eve.Cyan);
        var pdf = TapeRibbon.BigTool("📕⬇", "PDF", "Export the tape, with its pictures, to a PDF document (A4, pages numbered)", OnExportPdf);
        var exchange = TapeRibbon.Group("Import / Export", false, word, pdf, exportJson, importJson);

        var font = _ribbon.FontGroup();
        var paragraph = _ribbon.ParagraphGroup();
        var styles = _ribbon.StylesGroup();

        _review = TapeRibbon.BigTool("✨", "AI", $"AI review of the whole document, its text and its pictures, by the vision model of Ollama ({_vm.ReviewModel}, visionmodel in config.yml, on this machine): points to improve, coherence of the purpose, the pictures, a mark", OnReview);
        var review = TapeRibbon.Group("Review", false, _review);
        review.Visible = _vm.CanReview;

        var calculator = TapeRibbon.BigTool("🧮", "Calculator", "Open the scientific calculator in a window of its own (its calculations with = go to the tape)", OnOpenCalculator);
        var tools = TapeRibbon.Group("Tools", true, calculator);

        var pictures = _ribbon.PicturesGroup("Insert pictures at the caret (copied into the pictures folder of the calculator, Pictures/kaonomi/maths by default)", OnUploadImage,
            "Generate an image with Fooocus from a prompt, then insert it at the caret (saved in Pictures/kaonomi/maths)");
        var links = _ribbon.LinksGroup();
        var graphButton = TapeRibbon.BigTool("📈", "Graph", "Open the graph of functions of x in a window of its own (📷 Camera adds a picture of it to the tape)", OnOpenGraph);
        var graph = TapeRibbon.Group("Graph", false, graphButton);
        var code = _ribbon.CodeGroup();

