    /// <summary>New: saves the document being worked on, then empties the tape (kept when the save fails).</summary>
    private async void OnNewDocument()
    {
        if (!_vm.CanUseDocuments && !string.IsNullOrWhiteSpace(_vm.Tape))
        {
            if (await Dialogs.Confirm("New document", "The Kaonomi server is not available: the document cannot be saved. Empty the tape anyway?", "Empty the tape"))
                Bind.Run(_vm.ClearTapeCommand);
            return;
        }
        _new.Disabled = true;
        ShowStatus("Saving the document…", Eve.Eve.Muted, keep: true);
        try
        {
            var done = await _vm.NewDocumentAsync();
            ShowStatus("✓ " + done);
        }
        catch (Exception ex) when (ex is InvalidOperationException or System.Net.Http.HttpRequestException
                                       or TaskCanceledException or System.Text.Json.JsonException)
        {
            ShowStatus("Not saved, the tape is kept: " + ex.Message, Eve.Eve.Red, keep: true);
            ActivityLog.Error("Calculator", "New document: the save failed, the tape is kept", ex);
        }
        finally
        {
            if (GodotObject.IsInstanceValid(_new))
                _new.Disabled = false;
        }
    }

    private static string SafeName(string title, string fallback) =>
        string.Concat((title.Length > 0 ? title : fallback).Split(System.IO.Path.GetInvalidFileNameChars())).Trim();

    /// <summary>The tape, its pictures embedded, in a Word document chosen in the save dialog.</summary>
    private async void OnExportWord()
    {
        var file = await Dialogs.SaveFile("Export the tape to Word", $"kaonomi-tape-{DateTime.Now:yyyyMMdd-HHmmss}.docx", ["*.docx ; Word document"]);
        if (file is null)
            return;
        if (!file.EndsWith(".docx", StringComparison.OrdinalIgnoreCase))
            file += ".docx";
        try
        {
            int pictures;
            await using (var stream = System.IO.File.Create(file))
                pictures = await TapeWordExport.WriteAsync(stream, _vm.Tape, LoadPngAsync);
            ShowStatus($"✓ Exported to {System.IO.Path.GetFileName(file)}" + (pictures > 0 ? $" ({pictures} picture(s))" : string.Empty));
        }
        catch (Exception ex) when (ex is System.IO.IOException or UnauthorizedAccessException)
        {
            ShowStatus($"Not exported: {ex.Message}", Eve.Eve.Red);
        }
    }

    /// <summary>The tape, its pictures embedded, in a PDF document chosen in the save dialog.</summary>
    private async void OnExportPdf()
    {
        var title = _vm.SuggestedTitle();
        var file = await Dialogs.SaveFile("Export the tape to PDF", $"{SafeName(title, "kaonomi-tape")}-{DateTime.Now:yyyyMMdd-HHmmss}.pdf", ["*.pdf ; PDF document"]);
        if (file is null)
            return;
        if (!file.EndsWith(".pdf", StringComparison.OrdinalIgnoreCase))
            file += ".pdf";
        try
        {
            ShowStatus("Writing the PDF…", keep: true);
            int pictures;
            await using (var stream = System.IO.File.Create(file))
                pictures = await TapePdfExport.WriteAsync(stream, _vm.Tape, LoadPngAsync, title.Length > 0 ? title : "KAONOMI · Work");
            ShowStatus($"✓ Exported to {System.IO.Path.GetFileName(file)}" + (pictures > 0 ? $" ({pictures} picture(s))" : string.Empty));
            ActivityLog.Info("Calculator", $"Tape exported to PDF: {file} ({pictures} picture(s))");
        }
        catch (Exception ex) when (ex is System.IO.IOException or UnauthorizedAccessException or InvalidOperationException)
        {
            ShowStatus($"Not exported: {ex.Message}", Eve.Eve.Red);
            ActivityLog.Error("Calculator", "PDF export of the tape failed", ex);
        }
    }

    private static async Task<TapeWordExport.Picture?> LoadPngAsync(string path)
    {
        using var bitmap = await PictureLibrary.DecodeAsync(path, 1600, CancellationToken.None);
        if (bitmap is null)
            return null;
        using var png = new System.IO.MemoryStream();
#pragma warning disable CS0618
        bitmap.Save(png);
#pragma warning restore CS0618
        return new(png.ToArray(), bitmap.PixelSize.Width, bitmap.PixelSize.Height);
    }

    /// <summary>⬇ JSON: the tape in a JSON file, its pictures inside it in base 64 (with its title).</summary>
    private async void OnExportJson()
    {
        var title = _vm.SuggestedTitle();
        var file = await Dialogs.SaveFile("Export the tape to JSON", $"{SafeName(title, "kaonomi-tape")}-{DateTime.Now:yyyyMMdd-HHmmss}.json", ["*.json ; JSON"]);
        if (file is null)
            return;
        if (!file.EndsWith(".json", StringComparison.OrdinalIgnoreCase))
            file += ".json";
        try
        {
            var (json, embedded, missing) = TapeJson.Export(_vm.Tape, title);
            await System.IO.File.WriteAllTextAsync(file, json, new System.Text.UTF8Encoding(false));
            ShowStatus($"✓ Exported to {System.IO.Path.GetFileName(file)} ({embedded} picture(s) inside)" + (missing.Count > 0 ? $", {missing.Count} not found" : string.Empty));
            ActivityLog.Info("Calculator", $"Tape exported to JSON: {file}, {embedded} picture(s) embedded, {missing.Count} not found");
        }
        catch (Exception ex) when (ex is System.IO.IOException or UnauthorizedAccessException)
        {
            ShowStatus($"Not exported: {ex.Message}", Eve.Eve.Red);
        }
    }

    /// <summary>⬆ JSON: a tape exported in JSON replaces the tape (Ctrl / ⌘ + Z brings it back), its pictures written into the pictures folder.</summary>
    private async void OnImportJson()
    {
        var file = await Dialogs.OpenFile("Import a tape from JSON", ["*.json ; JSON"]);
        if (file is null)
            return;
        try
        {
            var json = await System.IO.File.ReadAllTextAsync(file);
            var (content, title, pictures) = TapeJson.Import(json, _vm.GraphPicturesDirectory);
            _editor.ReplaceAll(content);
            _vm.ImportedTape(title);
            ShowStatus($"✓ Imported {System.IO.Path.GetFileName(file)} ({pictures} picture(s) into {System.IO.Path.GetFileName(_vm.GraphPicturesDirectory)})");
            ActivityLog.Info("Calculator", $"Tape imported from JSON: {file}, {pictures} picture(s) written to {_vm.GraphPicturesDirectory}");
        }
        catch (Exception ex) when (ex is System.IO.IOException or System.IO.InvalidDataException or UnauthorizedAccessException)
        {
            ShowStatus($"Not imported: {ex.Message}", Eve.Eve.Red);
        }
    }

