    /// <summary>
    /// The 💾 panel: title, category, author, security classification and description of the document (written by the
    /// LLM as soon as the panel opens; ✨ Rewrite writes it again), then Save: a new version of its document (or a new one).
    /// </summary>
    private void ShowSaveFlyout(Control anchor)
    {
        var document = _vm.CurrentDocument;
        var heading = Eve.Eve.Text_(document is null
            ? "Save the tape as a new document"
            : $"Save the tape as version {(document.Latest?.Version ?? 0) + 1} of “{document.Title}”", Eve.Eve.TextBright, 13);
        var title = new LineEdit { PlaceholderText = "Title", Text = _vm.SuggestedTitle() };
        var category = new Dropdown();
        category.SetItems(CalculatorViewModel.DocumentCategories);
        var currentCategory = document?.Category is { } c && CalculatorViewModel.DocumentCategories.Contains(c) ? c : "math";
        category.Selected = Array.IndexOf(CalculatorViewModel.DocumentCategories, currentCategory);
        var author = new LineEdit { PlaceholderText = "Author", Text = document?.Author ?? Environment.UserName };
        var classification = new LineEdit { PlaceholderText = "public, internal, confidential…", Text = document?.SecurityClassification ?? string.Empty };
        var description = new TextEdit { WrapMode = TextEdit.LineWrappingMode.Boundary, CustomMinimumSize = new Vector2(0, 96), PlaceholderText = "Description" };
        var rewrite = Ui.Action("✨ REWRITE", () => { }, tooltip: "Ask the LLM to write the description again from the tape");
        var descriptionLabel = Eve.Eve.Caption("Description");
        var asNew = new CheckBox { Text = "Save as a new document", Visible = document is not null };
        var status = Eve.Eve.Text_("", Eve.Eve.Muted, 11, wrap: true);
        status.CustomMinimumSize = new Vector2(380, 0);
        Button save = null!;

        CancellationTokenSource? writing = null;
        Task? describing = null;
        void Describe()
        {
            writing?.Cancel();
            var cancellation = writing = new CancellationTokenSource(TimeSpan.FromMinutes(2));
            description.Editable = false;
            rewrite.Disabled = true;
            descriptionLabel.Text = "DESCRIPTION · THE LLM IS WRITING IT…";
            describing = WriteAsync();

            async Task WriteAsync()
            {
                try
                {
                    var text = await _vm.WriteDescriptionAsync(title.Text, cancellation.Token);
                    if (!GodotObject.IsInstanceValid(description))
                        return;
                    description.Text = text;
                    descriptionLabel.Text = "DESCRIPTION · WRITTEN BY THE LLM (YOU CAN CHANGE IT)";
                }
                catch (OperationCanceledException) when (cancellation.IsCancellationRequested && writing != cancellation)
                {
                }
                catch (Exception ex) when (ex is OperationCanceledException or System.Net.Http.HttpRequestException
                                               or InvalidOperationException or System.Text.Json.JsonException)
                {
                    if (!GodotObject.IsInstanceValid(description))
                        return;
                    descriptionLabel.Text = "DESCRIPTION · NOT WRITTEN BY THE LLM: TYPE IT";
                    status.Text = $"The LLM did not write the description: {ex.Message}";
                }
                finally
                {
                    if (writing == cancellation && GodotObject.IsInstanceValid(description))
                    {
                        description.Editable = true;
                        rewrite.Disabled = false;
                    }
                }
            }
        }
        rewrite.Pressed += Describe;

        save = Ui.Action("💾 SAVE", async () =>
        {
            save.Disabled = true;
            try
            {
                if (describing is { IsCompleted: false } pending)
                {
                    status.Text = "Waiting for the description…";
                    try { await pending; } catch (Exception) { /* reported by Describe */ }
                }
                status.Text = "Saving…";
                var saved = await _vm.SaveDocumentAsync(title.Text, author.Text,
                    category.Selected >= 0 ? CalculatorViewModel.DocumentCategories[category.Selected] : null,
                    classification.Text, description.Text, asNew.ButtonPressed);
                _overlay.Close();
                ShowStatus($"✓ Saved: {saved.Title} · v{saved.Latest?.Version}");
            }
            catch (Exception ex) when (ex is System.Net.Http.HttpRequestException or InvalidOperationException
                                           or TaskCanceledException or System.Text.Json.JsonException)
            {
                if (!GodotObject.IsInstanceValid(status))
                    return;
                status.Text = $"Not saved: {ex.Message}";
                save.Disabled = false;
            }
        }, primary: true);

        var fields = Ui.Grid(2);
        fields.AddChild(Ui.Field("Category", category));
        fields.AddChild(Ui.Field("Security classification", classification));
        var column = Ui.Column(8, heading, Ui.Field("Title", title), fields, Ui.Field("Author", author),
            Ui.Row(6, Ui.Fill(descriptionLabel), rewrite), description, asNew, Ui.Row(8, save), status);
        column.CustomMinimumSize = new Vector2(380, 0);
        _overlay.Show(column, anchor, closed: () => writing?.Cancel());
        Callable.From(() => title.GrabFocus()).CallDeferred();
        Describe();
    }

    /// <summary>
    /// The 📂 panel: the 3 documents the user worked on last, or the documents found (fuzzy search as you type); a
    /// double-click, Enter or Open puts the latest version of the document in the tape.
    /// </summary>
    private void ShowLoadFlyout(Control anchor)
    {
        var search = new LineEdit { PlaceholderText = "Search: title, description, content (typos allowed)" };
        var label = Eve.Eve.Text_("", Eve.Eve.Muted, 11);
        var list = new VBoxContainer();
        list.AddThemeConstantOverride("separation", 2);
        var listScroll = Ui.Scroll(list);
        listScroll.CustomMinimumSize = new Vector2(0, 260);
        listScroll.SizeFlagsVertical = Control.SizeFlags.Fill;
        var hint = Eve.Eve.Text_("Opening replaces the tape (Ctrl / ⌘ + Z brings it back).", Eve.Eve.Muted, 11, wrap: true);
        DocumentEntry? selected = null;
        var documents = new List<DocumentEntry>();
        var rows = new List<Button>();
        Button open = null!;

        void Open()
        {
            if (selected is not { } document)
                return;
            _overlay.Close();
            _editor.ReplaceAll(_vm.OpenDocument(document));
            ShowStatus($"✓ Opened: {document.Title} · v{document.Latest?.Version ?? 0}");
        }
        void Select(int index)
        {
            selected = index >= 0 && index < documents.Count ? documents[index] : null;
            for (var i = 0; i < rows.Count; i++)
                rows[i].SetPressedNoSignal(i == index);
            open.Disabled = selected is null;
        }
        void Show(IReadOnlyList<DocumentEntry> found)
        {
            foreach (var child in list.GetChildren())
                child.QueueFree();
            documents = found.ToList();
            rows.Clear();
            for (var i = 0; i < documents.Count; i++)
            {
                var document = documents[i];
                var index = i;
                var details = string.Join(" · ", new[]
                {
                    document.Category, $"v{document.Latest?.Version ?? 0}", document.Date?.LocalDateTime.ToString("yyyy-MM-dd HH:mm"), document.Author
                }.Where(s => !string.IsNullOrWhiteSpace(s)));
                var row = new Button { ToggleMode = true, SizeFlagsHorizontal = Control.SizeFlags.ExpandFill, FocusMode = Control.FocusModeEnum.None, MouseDefaultCursorShape = Control.CursorShape.PointingHand };
                row.AddThemeStyleboxOverride("normal", Eve.Eve.Box(Eve.Eve.Sunken(0.15f), Eve.Eve.Edge with { A = 0.15f }, 6));
                var titleLabel = Eve.Eve.Text_(string.IsNullOrWhiteSpace(document.Title) ? "noname" : document.Title, Eve.Eve.TextBright, 13);
                titleLabel.TextOverrunBehavior = TextServer.OverrunBehavior.TrimEllipsis;
                var detailsLabel = Eve.Eve.Text_(details, Eve.Eve.Muted, 11);
                var descriptionLabel = Eve.Eve.Text_(document.Description ?? string.Empty, Eve.Eve.Text with { A = 0.8f }, 11, wrap: true);
                descriptionLabel.MaxLinesVisible = 2;
                descriptionLabel.TextOverrunBehavior = TextServer.OverrunBehavior.TrimEllipsis;
                descriptionLabel.Visible = !string.IsNullOrWhiteSpace(document.Description);
                var content = Ui.Column(1, titleLabel, detailsLabel, descriptionLabel);
                foreach (var child in new Control[] { content, titleLabel, detailsLabel, descriptionLabel })
                    child.MouseFilter = Control.MouseFilterEnum.Ignore;
                var margin = Ui.Margin(content, 8, 4, 8, 4);
                margin.MouseFilter = Control.MouseFilterEnum.Ignore;
                margin.SetAnchorsAndOffsetsPreset(Control.LayoutPreset.FullRect);
                row.AddChild(margin);
                row.CustomMinimumSize = new Vector2(0, descriptionLabel.Visible ? 72 : 44);
                row.Pressed += () => Select(index);
                row.GuiInput += e =>
                {
                    if (e is InputEventMouseButton { Pressed: true, DoubleClick: true, ButtonIndex: MouseButton.Left })
                    {
                        Select(index);
                        Open();
                    }
                };
                rows.Add(row);
                list.AddChild(row);
            }
            Select(-1);
        }

        CancellationTokenSource? query = null;
        async void Refresh(int delay)
        {
            query?.Cancel();
            var cancellation = query = new CancellationTokenSource();
            try
            {
                await Task.Delay(delay, cancellation.Token);
                var term = search.Text.Trim();
                label.Text = term.Length == 0 ? "Recent documents · loading…" : "Searching…";
                var found = term.Length == 0
                    ? await _vm.RecentDocumentsAsync(cancellation.Token)
                    : await _vm.SearchDocumentsAsync(term, cancellation.Token);
                if (cancellation.IsCancellationRequested || !GodotObject.IsInstanceValid(list))
                    return;
                Show(found);
                label.Text = term.Length == 0
                    ? found.Count == 0 ? "No document saved yet (💾 saves the tape)" : "Recent documents · the ones you worked on last"
                    : found.Count == 0 ? "No document found" : $"{found.Count} document(s) found";
            }
            catch (OperationCanceledException)
            {
            }
            catch (Exception ex) when (ex is System.Net.Http.HttpRequestException or System.Text.Json.JsonException)
            {
                if (GodotObject.IsInstanceValid(label))
                    label.Text = $"The Kaonomi server did not answer: {ex.Message}";
            }
        }

        open = Ui.Action("📂 OPEN", Open, primary: true);
        open.Disabled = true;
        search.TextChanged += _ => Refresh(300);
        search.GuiInput += e =>
        {
            if (e is InputEventKey { Pressed: true, Keycode: Key.Down } && documents.Count > 0)
            {
                Select(Math.Min(documents.Count - 1, documents.IndexOf(selected!) + 1));
                search.AcceptEvent();
            }
            else if (e is InputEventKey { Pressed: true, Keycode: Key.Up } && documents.Count > 0)
            {
                Select(Math.Max(0, documents.IndexOf(selected!) - 1));
                search.AcceptEvent();
            }
        };
        search.TextSubmitted += _ =>
        {
            if (documents.Count == 0)
                return;
            if (selected is null)
                Select(0);
            Open();
        };
        var column = Ui.Column(8, Eve.Eve.Text_("Open a document", Eve.Eve.TextBright, 13), search, label, listScroll, hint, Ui.Row(8, open));
        column.CustomMinimumSize = new Vector2(420, 0);
        _overlay.Show(column, anchor, closed: () => query?.Cancel());
        Callable.From(() => search.GrabFocus()).CallDeferred();
        Refresh(0);
    }
