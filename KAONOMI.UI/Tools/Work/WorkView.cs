/// <summary>
/// /work: the tape of the calculations as a rich document. A ribbon in the manner of Word, fixed while the document
/// scrolls, with three tabs (the status of the window at the right of the tabs). Home: New (the document saved first,
/// then the tape emptied), Save / Open (documents of the Kaonomi server), Word, PDF, Export JSON, Import JSON, the font,
/// size, B I U S, color and clear formatting of the selection, the alignment, the paragraph style, ✨ AI review (waiting
/// popup with Cancel), the calculator (its own window). Insert: pictures, a picture generated with Fooocus, crop the
/// selected picture, link, the graph (its own window), code, code generated by the LLM. View: the zoom of the page (also
/// Ctrl / ⌘ + wheel). Right click on the tape: correct the spelling (the language identified first) and rewrite for
/// readability (waiting popup), evaluate, translate, annotate, cut, copy, paste. A double-click on a picture opens it in
/// the image analysis window; pictures dropped from the Finder / Explorer are copied into the pictures folder of the
/// calculator and inserted where they fall.
/// </summary>
[ToolView(typeof(CalculatorViewModel), "Work", "🧮", 1180, 760)]
public sealed class WorkView : IToolView
{
    public Control Build(object viewModel, Shell shell) => new WorkPage((CalculatorViewModel)viewModel, shell).Root;
}

/// <summary>The controls and the actions of one window of /work.</summary>
internal sealed class WorkPage
{
    private readonly CalculatorViewModel _vm;
    private readonly Shell _shell;
    private readonly TapeEditor _editor;
    private readonly Overlay _overlay = new();
    private readonly TextBlock _status;
    private readonly TapeRibbon _ribbon;
    private Button _review = null!, _new = null!;
    private DeskWindow? _window;

    public WorkPage(CalculatorViewModel vm, Shell shell)
    {
        _vm = vm;
        _shell = shell;
        _editor = new TapeEditor
        {
            Placeholder = "The calculations done with = are written here, and kept. Type your notes anywhere; select text to format it."
        };
        _status = Ui.Label("", Ui.Green, 11);
        _status.MaxWidth = 520;
        Root = new Grid();
        _ribbon = new TapeRibbon(_editor, _overlay, shell, Root, _status, vm, "Calculator", "the tape", "work", _ => _vm.GraphPicturesDirectory);

        // The tape, both ways.
        _editor.TextCommitted += text => _vm.Tape = text;
        Ui.When(_editor, vm, () => _editor.Text = vm.Tape, nameof(vm.Tape));
        _editor.LoadImage = vm.LoadTapeImageAsync;
        _editor.OpenImage = OpenImageAnalysis;

        // The document (its title, version and date) is the title of the window; the status goes at the right of the
        // tabs of the ribbon: nothing above the ribbon.
        Ui.When(Root, vm, UpdateTitle, nameof(vm.DocumentCaption));

        // The page: the ribbon fixed above, the document scrolling below.
        var scroll = new ScrollViewer
        {
            Content = _editor,
            HorizontalScrollBarVisibility = Avalonia.Controls.Primitives.ScrollBarVisibility.Disabled,
            VerticalScrollBarVisibility = Avalonia.Controls.Primitives.ScrollBarVisibility.Auto
        };
        var ribbon = BuildRibbon();
        DockPanel.SetDock(ribbon, Avalonia.Controls.Dock.Top);
        var page = new Border
        {
            Background = WorkPalette.PageBrush,
            BorderBrush = Ui.Edge,
            BorderThickness = new Thickness(1),
            Child = new DockPanel { LastChildFill = true, Children = { ribbon, scroll } }
        };
        Root.Children.Add(new Border { Padding = new Thickness(8, 6, 8, 8), Child = page });

        // Pictures dropped from the Finder / Explorer.
        DragDrop.SetAllowDrop(Root, true);
        Root.AddHandler(DragDrop.DragOverEvent, OnDragOver);
        Root.AddHandler(DragDrop.DropEvent, OnDrop);

        Root.AttachedToVisualTree += (_, _) => WorkUi.Later(OnShown);
    }

    /// <summary>The content of the window.</summary>
    public Grid Root { get; }

    /// <summary>The title of the window: Work, then the document (title, version, date) when there is one.</summary>
    private void UpdateTitle()
    {
        if (WorkUi.WindowOf(Root) is not { } window)
            return;
        // Without a document the caption is a sentence about the tape: the title stays Work.
        var caption = _vm.CurrentDocument is null ? string.Empty : _vm.DocumentCaption.Replace("📄", string.Empty).Trim();
        WorkUi.SetTitle(window, caption.Length == 0 ? "Work" : $"Work · {caption}");
    }

    private void OnShown()
    {
        UpdateTitle();
        // The calculator and the graph belong to this window: they close with it.
        if (_window is null && WorkUi.WindowOf(Root) is { } window)
        {
            _window = window;
            window.Closed += () =>
            {
                if (_calculator is not null)
                    _shell.Close(_calculator);
                if (_graph is not null)
                    _shell.Close(_graph);
            };
        }
        _editor.Focus();
    }

