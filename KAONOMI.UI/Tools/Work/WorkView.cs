    /// <summary>✨ AI: the whole document (text and pictures) reviewed by the vision model, with the waiting popup and Cancel.</summary>
    private async void OnReview()
    {
        if (_editor.IsBusy)
            return;
        if (string.IsNullOrWhiteSpace(_vm.Tape))
        {
            ShowStatus("The document is empty: nothing to review", Ui.Warm);
            return;
        }
        var model = _vm.ReviewModel;
        _editor.IsBusy = true;
        _review.IsEnabled = false;
        ShowStatus($"✨ {model} is reviewing the document (text and pictures)…", Ui.Muted, keep: true);
        string? markdown = null, error = null;
        var pictures = 0;
        using var cancel = new CancellationTokenSource(TimeSpan.FromMinutes(15));
        var busy = BusyPopup.Show(Root, "AI review", $"{model} reads the document, its text and its pictures, and writes its critique…", cancel);
        var cancelled = false;
        try
        {
            (markdown, pictures) = await _vm.ReviewDocumentAsync(cancel.Token);
        }
        catch (OperationCanceledException) when (cancel.IsCancellationRequested && busy.IsCancelledByUser)
        {
            cancelled = true;
        }
        catch (Exception ex) when (ex is System.Net.Http.HttpRequestException or InvalidOperationException
                                       or OperationCanceledException or System.Text.Json.JsonException)
        {
            error = ex is OperationCanceledException ? "no answer after 15 minutes" : ex.Message;
            ActivityLog.Error("Calculator", "AI review of the document failed", ex);
        }
        finally
        {
            busy.Finish();
            _editor.IsBusy = false;
            _review.IsEnabled = true;
            _ribbon.ClearStatus();
        }
        if (cancelled)
        {
            ShowStatus("AI review cancelled", Ui.Muted);
            ActivityLog.Info("Calculator", "AI review of the document cancelled");
            return;
        }
        var excerpt = System.Text.RegularExpressions.Regex.Replace(_vm.Tape, @"(<p[^>]*>)?!\[[^\]]*\]\([^)]*\)(</p>)?", "[image]");
        WorkWindows.Evaluation(_shell, excerpt, model, markdown, error, "✨ AI review",
            $"Strengths, coherence of the purpose, the pictures, points to improve and a mark · {model} · {pictures} picture(s) read");
    }

