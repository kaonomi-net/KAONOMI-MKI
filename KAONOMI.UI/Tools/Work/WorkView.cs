    private static readonly string[] PictureFilters = ["*.png, *.jpg, *.jpeg, *.gif, *.webp, *.bmp, *.heic, *.heif, *.tif, *.tiff ; Pictures"];

    /// <summary>🖼: pictures chosen in a file dialog, copied into the pictures folder of the calculator, inserted at the caret.</summary>
    private async void OnUploadImage()
    {
        var files = await Dialogs.OpenFiles("Insert pictures in the tape", PictureFilters);
        if (files.Length == 0)
            return;
        var directory = _vm.GraphPicturesDirectory;
        var copied = new List<string>();
        try
        {
            System.IO.Directory.CreateDirectory(directory);
            foreach (var file in files)
            {
                var target = UniquePath(directory, System.IO.Path.GetFileName(file));
                System.IO.File.Copy(file, target);
                copied.Add(target);
                ActivityLog.Info("Calculator", $"Picture uploaded to the tape: {target}");
            }
        }
        catch (Exception ex) when (ex is System.IO.IOException or UnauthorizedAccessException)
        {
            ShowStatus($"Not copied: {ex.Message}", Ui.Red);
        }
        if (copied.Count == 0)
            return;
        _editor.InsertImages(copied);
        ShowStatus(copied.Count == 1 ? "✓ Picture added" : $"✓ {copied.Count} pictures added");
    }

    private static string[] DroppedFiles(DragEventArgs e) =>
        e.DataTransfer.TryGetFiles()?.Select(f => f.TryGetLocalPath()).OfType<string>().ToArray() ?? [];

    private void OnDragOver(object? sender, DragEventArgs e)
    {
        e.DragEffects = DroppedFiles(e).Any(PictureLibrary.IsPicture) ? DragDropEffects.Copy : DragDropEffects.None;
        e.Handled = true;
    }

    /// <summary>Pictures dropped on the window: copied into the pictures folder, inserted where they fall (or at the caret).</summary>
    private void OnDrop(object? sender, DragEventArgs e)
    {
        var pictures = DroppedFiles(e).Where(PictureLibrary.IsPicture).ToList();
        e.Handled = true;
        if (pictures.Count == 0)
            return;
        var prepared = CopyDroppedImages(pictures);
        if (prepared.Count == 0)
            return;
        var at = e.GetPosition(_editor);
        if (new Rect(_editor.Bounds.Size).Contains(at))
            _editor.InsertImagesAt(prepared, at);
        else
            _editor.InsertImages(prepared);
    }

    private List<string> CopyDroppedImages(IReadOnlyList<string> paths)
    {
        var directory = System.IO.Path.GetFullPath(_vm.GraphPicturesDirectory);
        var result = new List<string>();
        var copied = 0;
        foreach (var path in paths)
        {
            var full = System.IO.Path.GetFullPath(path);
            if (string.Equals(System.IO.Path.GetDirectoryName(full), directory.TrimEnd(System.IO.Path.DirectorySeparatorChar),
                    OperatingSystem.IsLinux() ? StringComparison.Ordinal : StringComparison.OrdinalIgnoreCase))
            {
                result.Add(full);
                continue;
            }
            try
            {
                System.IO.Directory.CreateDirectory(directory);
                var target = UniquePath(directory, System.IO.Path.GetFileName(full));
                System.IO.File.Copy(full, target);
                result.Add(target);
                copied++;
                ActivityLog.Info("Calculator", $"Picture dropped on the tape, copied to {target}");
            }
            catch (Exception ex) when (ex is System.IO.IOException or UnauthorizedAccessException)
            {
                ShowStatus($"Not copied: {ex.Message}", Ui.Red);
            }
        }
        if (copied > 0)
            ShowStatus(copied == 1 ? "✓ Picture copied into the pictures folder of the calculator" : $"✓ {copied} pictures copied into the pictures folder of the calculator");
        return result;
    }

    private static string UniquePath(string directory, string name)
    {
        var stem = System.IO.Path.GetFileNameWithoutExtension(name);
        var extension = System.IO.Path.GetExtension(name);
        var path = System.IO.Path.Combine(directory, name);
        for (var i = 2; System.IO.File.Exists(path); i++)
            path = System.IO.Path.Combine(directory, $"{stem}-{i}{extension}");
        return path;
    }

