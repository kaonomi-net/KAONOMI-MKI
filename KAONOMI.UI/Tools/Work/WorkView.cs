    /// <summary>
    /// The 💾 panel: title, category, author, security classification and description of the document (written by the
    /// LLM as soon as the panel opens; ✨ Rewrite writes it again), then Save: a new version of its document (or a new one).
    /// </summary>
    private void ShowSaveFlyout(Control anchor)
    {
        var document = _vm.CurrentDocument;
        var heading = Ui.Label(document is null
            ? "Save the tape as a new document"
            : $"Save the tape as version {(document.Latest?.Version ?? 0) + 1} of “{document.Title}”", Ui.TextBright, 13, wrap: true);
        var title = new TextBox { PlaceholderText = "Title", Text = _vm.SuggestedTitle() };
        var category = new Dropdown { HorizontalAlignment = HorizontalAlignment.Stretch };
        var currentCategory = document?.Category is { } c && CalculatorViewModel.DocumentCategories.Contains(c) ? c : "math";
        category.SetItems(CalculatorViewModel.DocumentCategories, Array.IndexOf(CalculatorViewModel.DocumentCategories, currentCategory));
        var author = new TextBox { PlaceholderText = "Author", Text = document?.Author ?? Environment.UserName };
        var classification = new TextBox { PlaceholderText = "public, internal, confidential…", Text = document?.SecurityClassification ?? string.Empty };
        var description = new TextBox { TextWrapping = TextWrapping.Wrap, AcceptsReturn = true, MinHeight = 96, PlaceholderText = "Description", VerticalContentAlignment = VerticalAlignment.Top };
        var rewrite = Ui.Button("✨ REWRITE", null, "Ask the LLM to write the description again from the tape");
        var descriptionLabel = Ui.Caption("Description");
        var asNew = new CheckBox { Content = "Save as a new document", IsVisible = document is not null };
        var status = Ui.Label("", Ui.Muted, 11, wrap: true);
        Button save = null!;

        CancellationTokenSource? writing = null;
        Task? describing = null;
        void Describe()
        {
            writing?.Cancel();
            var cancellation = writing = new CancellationTokenSource(TimeSpan.FromMinutes(2));
            description.IsReadOnly = true;
            rewrite.IsEnabled = false;
            descriptionLabel.Text = "DESCRIPTION · THE LLM IS WRITING IT…";
            describing = WriteAsync();

            async Task WriteAsync()
            {
                try
                {
                    var text = await _vm.WriteDescriptionAsync(title.Text ?? string.Empty, cancellation.Token);
                    description.Text = text;
                    descriptionLabel.Text = "DESCRIPTION · WRITTEN BY THE LLM (YOU CAN CHANGE IT)";
                }
                catch (OperationCanceledException) when (cancellation.IsCancellationRequested && writing != cancellation)
                {
                }
                catch (Exception ex) when (ex is OperationCanceledException or System.Net.Http.HttpRequestException
                                               or InvalidOperationException or System.Text.Json.JsonException)
                {
                    descriptionLabel.Text = "DESCRIPTION · NOT WRITTEN BY THE LLM: TYPE IT";
                    status.Text = $"The LLM did not write the description: {ex.Message}";
                }
                finally
                {
                    if (writing == cancellation)
                    {
                        description.IsReadOnly = false;
                        rewrite.IsEnabled = true;
                    }
                }
            }
        }
        rewrite.Click += (_, _) => Describe();

        save = Ui.Button("💾 SAVE", async () =>
        {
            save.IsEnabled = false;
            try
            {
                if (describing is { IsCompleted: false } pending)
                {
                    status.Text = "Waiting for the description…";
                    try { await pending; } catch (Exception) { /* reported by Describe */ }
                }
                status.Text = "Saving…";
                var saved = await _vm.SaveDocumentAsync(title.Text ?? string.Empty, author.Text,
                    category.Selected >= 0 ? CalculatorViewModel.DocumentCategories[category.Selected] : null,
                    classification.Text, description.Text, asNew.IsChecked == true);
                _overlay.Close();
                ShowStatus($"✓ Saved: {saved.Title} · v{saved.Latest?.Version}");
            }
            catch (Exception ex) when (ex is System.Net.Http.HttpRequestException or InvalidOperationException
                                           or TaskCanceledException or System.Text.Json.JsonException)
            {
                status.Text = $"Not saved: {ex.Message}";
                save.IsEnabled = true;
            }
        }, primary: true);

        var fields = new Grid { ColumnDefinitions = new ColumnDefinitions("*,*"), ColumnSpacing = 10 };
        var categoryField = WorkUi.Field("Category", category);
        var classificationField = WorkUi.Field("Security classification", classification);
        Grid.SetColumn(classificationField, 1);
        fields.Children.Add(categoryField);
        fields.Children.Add(classificationField);
        var column = Ui.Column(8, heading, WorkUi.Field("Title", title), fields, WorkUi.Field("Author", author),
            WorkUi.FillRow(6, descriptionLabel, rewrite), description, asNew, Ui.Row(8, save), status);
        column.Width = 400;
        _overlay.Show(column, anchor, closed: () => writing?.Cancel());
        WorkUi.Later(() => title.Focus());
        Describe();
    }

    /// <summary>
    /// The 📂 panel: the 3 documents the user worked on last, or the documents found (fuzzy search as you type); a
    /// double-click, Enter or Open puts the latest version of the document in the tape.
    /// </summary>
    private void ShowLoadFlyout(Control anchor)
    {
        var search = new TextBox { PlaceholderText = "Search: title, description, content (typos allowed)" };
        var label = Ui.Label("", Ui.Muted, 11);
        var list = Ui.Column(2);
        var listScroll = Ui.Scroll(list);
        listScroll.Height = 260;
        var hint = Ui.Label("Opening replaces the tape (Ctrl / ⌘ + Z brings it back).", Ui.Muted, 11, wrap: true);
        DocumentEntry? selected = null;
        var documents = new List<DocumentEntry>();
        var rows = new List<Button>();
        Button open = null!;

        void Open()
        {
            if (selected is not { } document)
                return;
            _overlay.Close();
            _editor.ReplaceAll(_vm.OpenDocument(document));
            ShowStatus($"✓ Opened: {document.Title} · v{document.Latest?.Version ?? 0}");
        }
        void Select(int index)
        {
            selected = index >= 0 && index < documents.Count ? documents[index] : null;
            for (var i = 0; i < rows.Count; i++)
            {
                rows[i].Background = i == index ? Ui.Header : Ui.Field;
                rows[i].BorderBrush = i == index ? Ui.Accent : Ui.Edge;
            }
            if (index >= 0 && index < rows.Count)
                rows[index].BringIntoView();
            open.IsEnabled = selected is not null;
        }
        void Show(IReadOnlyList<DocumentEntry> found)
        {
            list.Children.Clear();
            documents = found.ToList();
            rows.Clear();
            for (var i = 0; i < documents.Count; i++)
            {
                var document = documents[i];
                var index = i;
                var details = string.Join(" · ", new[]
                {
                    document.Category, $"v{document.Latest?.Version ?? 0}", document.Date?.LocalDateTime.ToString("yyyy-MM-dd HH:mm"), document.Author
                }.Where(s => !string.IsNullOrWhiteSpace(s)));
                var titleLabel = Ui.Label(string.IsNullOrWhiteSpace(document.Title) ? "noname" : document.Title, Ui.TextBright, 13);
                var detailsLabel = Ui.Label(details, Ui.Muted, 11);
                var descriptionLabel = Ui.Label(document.Description ?? string.Empty, Ui.Text, 11, wrap: true);
                descriptionLabel.MaxLines = 2;
                descriptionLabel.TextTrimming = TextTrimming.CharacterEllipsis;
                descriptionLabel.IsVisible = !string.IsNullOrWhiteSpace(document.Description);
                var row = new Button
                {
                    Content = Ui.Column(1, titleLabel, detailsLabel, descriptionLabel),
                    HorizontalAlignment = HorizontalAlignment.Stretch,
                    HorizontalContentAlignment = HorizontalAlignment.Left,
                    Focusable = false,
                    Padding = new Thickness(8, 4),
                    BorderThickness = new Thickness(1),
                    Cursor = new Cursor(StandardCursorType.Hand)
                };
                row.Click += (_, _) => Select(index);
                row.DoubleTapped += (_, _) =>
                {
                    Select(index);
                    Open();
                };
                rows.Add(row);
                list.Children.Add(row);
            }
            Select(-1);
        }

        CancellationTokenSource? query = null;
        async void Refresh(int delay)
        {
            query?.Cancel();
            var cancellation = query = new CancellationTokenSource();
            try
            {
                await Task.Delay(delay, cancellation.Token);
                var term = (search.Text ?? string.Empty).Trim();
                label.Text = term.Length == 0 ? "Recent documents · loading…" : "Searching…";
                var found = term.Length == 0
                    ? await _vm.RecentDocumentsAsync(cancellation.Token)
                    : await _vm.SearchDocumentsAsync(term, cancellation.Token);
                if (cancellation.IsCancellationRequested)
                    return;
                Show(found);
                label.Text = term.Length == 0
                    ? found.Count == 0 ? "No document saved yet (💾 saves the tape)" : "Recent documents · the ones you worked on last"
                    : found.Count == 0 ? "No document found" : $"{found.Count} document(s) found";
            }
            catch (OperationCanceledException)
            {
            }
            catch (Exception ex) when (ex is System.Net.Http.HttpRequestException or System.Text.Json.JsonException)
            {
                label.Text = $"The Kaonomi server did not answer: {ex.Message}";
            }
        }

        open = Ui.Button("📂 OPEN", Open, primary: true);
        open.IsEnabled = false;
        search.TextChanged += (_, _) => Refresh(300);
        search.AddHandler(InputElement.KeyDownEvent, (_, e) =>
        {
            if (e.Key == Key.Down && documents.Count > 0)
            {
                Select(Math.Min(documents.Count - 1, selected is null ? 0 : documents.IndexOf(selected) + 1));
                e.Handled = true;
            }
            else if (e.Key == Key.Up && documents.Count > 0)
            {
                Select(Math.Max(0, selected is null ? 0 : documents.IndexOf(selected) - 1));
                e.Handled = true;
            }
            else if (e.Key == Key.Enter)
            {
                e.Handled = true;
                if (documents.Count == 0)
                    return;
                if (selected is null)
                    Select(0);
                Open();
            }
        }, Avalonia.Interactivity.RoutingStrategies.Tunnel);
        var column = Ui.Column(8, Ui.Label("Open a document", Ui.TextBright, 13), search, label, listScroll, hint, Ui.Row(8, open));
        column.Width = 420;
        _overlay.Show(column, anchor, closed: () => query?.Cancel());
        WorkUi.Later(() => search.Focus());
        Refresh(0);
    }

