namespace KAONOMI.UI.Tools.Writing;

/// <summary>
/// /journal: the entry edited as it is shown, with the editor and the ribbon of /work (<see cref="TapePage"/>), as in the
/// Godot chat; the entry stays Markdown. The ribbon: Home starts with the Entry group (Previous entries, New entry, Save, Delete) and ends
/// with the Feeling group (the emoticons of the emotion of the entry), with font, paragraph and styles between; Insert:
/// pictures (linked where they are, not copied), a picture generated with Fooocus, links, code inserted or generated by the
/// LLM; Security: the password encrypting the entry (AES-256, from 12 characters) with 👁 and Unlock (Enter); View: zoom and
/// what is shown. The right click corrects the spelling, rewrites, evaluates or translates. Shortcuts: ⌘/Ctrl S saves, B I U,
/// K (link), E (inline code), 1 2 3 (headings). The mode of the entry (new, saved, its date) is the title of the window; the
/// status (not saved, error) is under the page. Pictures dropped from the file manager are inserted at the caret.
/// </summary>
[ToolView(typeof(JournalWindowViewModel), "Journal", "📓", 1250, 820)]
public sealed class JournalView : IToolView
{
    public Control Build(object viewModel, Shell shell)
    {
        var vm = (JournalWindowViewModel)viewModel;
        vm.ConfirmAsync = WritingUi.Confirm;

        var tape = new TapePage(shell, viewModel as ITapeAssistant, "Journal", "the journal entry", "journal",
            _ => JournalWindowViewModel.JournalPicturesDirectory,
            "Write your entry here… select text to format it (the ribbon above, or ⌘/Ctrl B, I, U).");
        var editor = tape.Editor;
        // The entry, both ways (Markdown; the view model encrypts and decrypts, the editor only sees the clear text).
        tape.Bind(vm, nameof(vm.Text));
        editor.LoadImage = vm.LoadImageAsync;
        editor.OpenImage = path => OpenImage(vm, shell, path);

        // The Entry group of the ribbon: previous entries, new entry, save, delete.
        var history = TapeRibbon.BigTool("🗂", "Previous", "Show / hide the previous entries (search, a click opens one)", () => vm.ShowHistory = !vm.ShowHistory);
        Ui.When(history, vm, () => TapeRibbon.SetOn(history, vm.ShowHistory), nameof(vm.ShowHistory));
        var newEntry = TapeRibbon.BigTool("📓", "New entry", "Start a new entry", () => Ui.Run(vm.NewEntryCommand));
        var save = TapeRibbon.BigTool("💾", "Save", "Save the entry (Ctrl+S / ⌘S)", () => Ui.Run(vm.SaveCommand));
        var delete = TapeRibbon.BigTool("🗑", "Delete", "Delete this entry", () => Ui.Run(vm.DeleteCommand));
        var entryGroup = TapeRibbon.Group("Entry", false, history, newEntry, save, delete);

        // The Password group (the Security tab): the password encrypting the entry, 👁, its state, Unlock.
        var password = new TextBox
        {
            PasswordChar = '●',
            PlaceholderText = "Password (12+ characters) to encrypt",
            Width = 240
        };
        ToolTip.SetTip(password, "With a password of at least 12 characters the entry is encrypted with AES-256 (key derived with PBKDF2-SHA256) before it is sent; the password is never saved: without it the entry cannot be read");
        password.Bind(TextBox.TextProperty, vm, nameof(vm.Password), Avalonia.Data.BindingMode.TwoWay);
        password.KeyDown += (_, e) =>
        {
            if (e.Key == Key.Enter)
            {
                Ui.Run(vm.UnlockCommand);
                e.Handled = true;
            }
        };
        var forget = Ui.Label("Don't forget your password", WritingUi.Amber, 10);
        forget.HorizontalAlignment = HorizontalAlignment.Center;
        var reveal = new ToggleButton { Content = "👁", Focusable = false, VerticalAlignment = VerticalAlignment.Top };
        ToolTip.SetTip(reveal, "Show / hide the password");
        reveal.IsCheckedChanged += (_, _) => password.RevealPassword = reveal.IsChecked == true;
        var info = Ui.Bound(vm, nameof(vm.PasswordInfo), Ui.Text, 12);
        info.MinWidth = 200;
        Ui.When(info, vm, () => info.Foreground = vm.IsPasswordValid ? Ui.Text : WritingUi.Amber, nameof(vm.IsPasswordValid), nameof(vm.PasswordInfo));
        var unlock = WritingUi.Command("🔓 UNLOCK", vm.UnlockCommand, primary: true, tooltip: "Decrypt this entry with the password").Visible(vm, nameof(vm.IsLocked));
        var passwordGroup = TapeRibbon.Group("Password", true, Ui.Column(1, password, forget), reveal, info, unlock);

        // The Feeling group: the emoticons of the emotions of the entry, the one chosen outlined, its name beside them.
        var feelings = Ui.Row(2);
        foreach (var feeling in vm.Feelings)
            feelings.Children.Add(FeelingButton(vm, feeling));
        var feelingLabel = Ui.Bound(vm, nameof(vm.FeelingLabel), Ui.Text, 12);
        feelingLabel.MinWidth = 110;
        var feelingGroup = TapeRibbon.Group("Feeling", true, feelings, feelingLabel);

        // History (hidden by default).
        var search = WritingUi.Line(vm, nameof(vm.HistorySearch), "Search in the entries…");
        search.KeyDown += (_, e) =>
        {
            if (e.Key == Key.Enter)
            {
                Ui.Run(vm.SearchHistoryCommand);
                e.Handled = true;
            }
        };
        var searchButton = WritingUi.Command("⟳", vm.SearchHistoryCommand, tooltip: "Search (Enter); empty: the last entries");
        searchButton.Margin = new Thickness(6, 0, 0, 0);
        var historyList = new StackPanel();
        var noEntry = WritingUi.Placeholder("No entry");
        noEntry.VerticalAlignment = VerticalAlignment.Top;
        WritingUi.Items(historyList, vm.History, item => HistoryRow(vm, item), noEntry);
        var searchRow = Ui.Dock((searchButton, Dock.Right), (search, Dock.Left));
        searchRow.Margin = new Thickness(0, 0, 0, 8);
        var historyPanel = WritingUi.Page([searchRow], new Panel { Children = { Ui.Scroll(historyList), noEntry } });
        historyPanel.Width = 300;
        var historyHolder = WritingUi.Margin(historyPanel, 10, 10, 0, 10).Visible(vm, nameof(vm.ShowHistory));

        // The page: the ribbon fixed above (the short messages at the right of its tabs), the entry below.
        var ribbon = tape.Ribbon;
        var picturesTooltip = $"Insert pictures at the caret (picked in {vm.PicturesDirectory}; linked where they are, not copied); resize them with the grip of their corner";
        var page = tape.Build(
            ("Home", [entryGroup, ribbon.FontGroup(), ribbon.ParagraphGroup(), ribbon.StylesGroup(), feelingGroup]),
            ("Insert", [ribbon.PicturesGroup(picturesTooltip, () => _ = InsertPicturesAsync(vm, editor),
                $"Generate an image with Fooocus from a prompt, then insert it at the caret (saved in {JournalWindowViewModel.JournalPicturesDirectory})"),
                ribbon.LinksGroup(), ribbon.CodeGroup()]),
            ("Security", [passwordGroup]),
            ("View", [ribbon.ZoomGroup()]));

        // The locked notice replaces the page until the entry is unlocked (the editor never sees the ciphertext); the
        // password stays reachable above it.
        var lockIcon = Ui.Label("🔒", null, 56);
        var lockTitle = Ui.Label("THIS ENTRY IS ENCRYPTED (AES-256)", Ui.TextBright, 15, wrap: true, bold: true);
        var lockHint = Ui.Label("Type its password below and press Unlock (Enter)", Ui.Muted, 13, wrap: true);
        var lockPassword = new TextBox { PasswordChar = '●', PlaceholderText = "Password", Width = 280 };
        lockPassword.Bind(TextBox.TextProperty, vm, nameof(vm.Password), Avalonia.Data.BindingMode.TwoWay);
        lockPassword.KeyDown += (_, e) =>
        {
            if (e.Key == Key.Enter)
            {
                Ui.Run(vm.UnlockCommand);
                e.Handled = true;
            }
        };
        var lockUnlock = WritingUi.Command("🔓 UNLOCK", vm.UnlockCommand, primary: true);
        var lockColumn = Ui.Column(10, lockIcon, lockTitle, lockHint, lockPassword, lockUnlock);
        foreach (var control in lockColumn.Children)
            control.HorizontalAlignment = HorizontalAlignment.Center;
        lockTitle.TextAlignment = lockHint.TextAlignment = TextAlignment.Center;
        lockColumn.VerticalAlignment = VerticalAlignment.Center;
        var locked = Ui.Box(lockColumn, 12, Ui.Field, WritingUi.Amber).Visible(vm, nameof(vm.IsLocked));
        page.Visible(vm, nameof(vm.IsLocked), invert: true);
        var pageArea = WritingUi.Margin(new Panel { Children = { page, locked } }, 10);

        var body = Ui.Dock((historyHolder, Dock.Left), (pageArea, Dock.Left));

        // Status: error dot, the text, not saved.
        var dirty = Ui.Label("● not saved", WritingUi.Amber, 12).Visible(vm, nameof(vm.IsDirty));
        var status = WritingUi.StatusBar(vm, nameof(vm.Status), nameof(vm.IsError), extra: dirty);

        var root = WritingUi.Page([], body, status);

        // The entry (its mode and date) is the title of the window.
        void UpdateTitle()
        {
            var caption = vm.ModeLabel.Trim();
            WritingUi.SetTitle(root, caption.Length == 0 ? "Journal" : $"Journal · {caption}");
        }
        Ui.When(root, vm, UpdateTitle, nameof(vm.ModeLabel));
        WritingUi.WhenInWindow(root, UpdateTitle);

        // Shortcuts of the journal (the editor has B, I, U, Ctrl / ⌘ + Alt + 0…3 itself): S saves, K links, E inline
        // code (nothing selected: a block of code), 1 2 3 headings (again: Normal).
        WritingUi.Shortcuts(root, key =>
        {
            if (WritingUi.IsCommand(key, Key.S))
                return WritingUi.Run(vm.SaveCommand);
            if (vm.IsLocked || !editor.IsFocused)
                return false;
            if (WritingUi.IsCommand(key, Key.K))
            {
                ribbon.ShowLinkFlyout();
                return true;
            }
            if (WritingUi.IsCommand(key, Key.E))
            {
                InlineCode(editor, ribbon);
                return true;
            }
            var kind = key.Key switch
            {
                Key.D1 => TapeParagraphKind.Heading1,
                Key.D2 => TapeParagraphKind.Heading2,
                Key.D3 => TapeParagraphKind.Heading3,
                _ => (TapeParagraphKind?)null
            };
            if (kind is not { } heading || !WritingUi.IsCommand(key, key.Key))
                return false;
            editor.SetParagraphKind(editor.CurrentParagraphKind == heading ? TapeParagraphKind.Normal : heading);
            ribbon.UpdateToolbar();
            return true;
        });

        // Pictures dropped from the file manager are inserted where they fall (or at the caret).
        DragDrop.SetAllowDrop(root, true);
        root.AddHandler(DragDrop.DropEvent, (_, e) =>
        {
            if (vm.IsLocked)
                return;
            var pictures = WritingFiles.Dropped(e).Where(PictureLibrary.IsPicture).ToList();
            if (pictures.Count == 0)
                return;
            tape.InsertDropped(pictures, e);
            vm.Status = $"{pictures.Count} picture(s) inserted; drag the corner of a picture to resize it";
            e.Handled = true;
        });

        WritingUi.FocusWhenShown(editor);
        return root;
    }

    /// <summary>The font of the inline code of the page (<c>`code`</c>).</summary>
    private const string CodeFont = "Cascadia Mono, Menlo, Consolas, monospace";

    /// <summary>⌘/Ctrl E: the selection (in one paragraph) in inline code, or out of it; nothing selected: the window of a block of code.</summary>
    private static void InlineCode(TapeEditor editor, TapeRibbon ribbon)
    {
        if (!editor.HasSelectedContent || editor.SelectedText.Contains('\n'))
        {
            ribbon.InsertCode();
            return;
        }
        var isCode = editor.CurrentStyle.Font == CodeFont;
        editor.ApplyStyle(s => isCode ? s with { Font = null } : s with { Font = CodeFont, Size = null, Color = null });
        ribbon.UpdateToolbar();
    }

    /// <summary>🖼: pictures picked in the Pictures folder, inserted at the caret with their path (not copied).</summary>
    private static async Task InsertPicturesAsync(JournalWindowViewModel vm, TapeEditor editor)
    {
        if (vm.IsLocked)
            return;
        var files = await Dialogs.OpenFiles("Insert pictures", WritingUi.PictureFilters, vm.PicturesDirectory);
        if (files.Length == 0)
            return;
        editor.InsertImages(files);
        vm.Status = $"{files.Length} picture(s) inserted; drag the corner of a picture to resize it";
    }

    /// <summary>A double-click on a picture: the image analysis window of /pictures (or the viewer of the system).</summary>
    private static void OpenImage(JournalWindowViewModel vm, Shell shell, string path)
    {
        if (vm.CreateAnalysis is not { } create || !System.IO.File.Exists(path))
        {
            PictureLibrary.OpenWithSystem(path);
            return;
        }
        shell.Open(create(path));
    }

    /// <summary>A round emoticon of an emotion, outlined when it is the one of the entry (again: cleared).</summary>
    private static Button FeelingButton(JournalWindowViewModel vm, JournalFeeling feeling)
    {
        var button = new Button
        {
            Content = feeling.Emoji,
            FontSize = 19,
            Width = 38,
            Height = 38,
            Padding = new Thickness(0),
            HorizontalContentAlignment = HorizontalAlignment.Center,
            VerticalContentAlignment = VerticalAlignment.Center,
            CornerRadius = new CornerRadius(19),
            Background = Brushes.Transparent,
            BorderThickness = new Thickness(2),
            Focusable = false,
            Cursor = new Cursor(StandardCursorType.Hand)
        };
        ToolTip.SetTip(button, feeling.Name);
        var hover = false;
        void Paint()
        {
            button.BorderBrush = feeling.IsSelected ? Ui.Accent : hover ? Ui.Edge : Brushes.Transparent;
            button.Opacity = feeling.IsSelected || hover ? 1 : 0.55;
        }
        button.PointerEntered += (_, _) => { hover = true; Paint(); };
        button.PointerExited += (_, _) => { hover = false; Paint(); };
        Ui.When(button, feeling, Paint, nameof(feeling.IsSelected));
        button.Click += (_, _) => Ui.Run(vm.ChooseFeelingCommand, feeling);
        return button;
    }

    /// <summary>A previous entry: its date, emotion and first words; a click opens it.</summary>
    private static Control HistoryRow(JournalWindowViewModel vm, JournalHistoryItem item)
    {
        var preview = WritingUi.Clamp(Ui.Label(item.Preview, Ui.Text, 12), 3);
        var content = Ui.Column(2, Ui.Row(6, Ui.Label(item.DateLabel, Ui.TextBright, 11), Ui.Label(item.Feeling, Ui.Text, 11)), preview);
        var row = WritingUi.ResultRow(vm, nameof(vm.EntryId), () => vm.EntryId is not null && vm.EntryId == item.Entry.Id,
            () => Ui.Run(vm.OpenEntryCommand, item), content, 52);
        ToolTip.SetTip(row, item.Preview);
        return row;
    }
}
