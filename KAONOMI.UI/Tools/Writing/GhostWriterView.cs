    /// <summary>✨ GENERATE: the summary written by the model of the chat, with the waiting dialog (Cancel).</summary>
    private static async Task GenerateSummaryAsync(GhostWriterWindowViewModel vm)
    {
        if (!vm.Assistant.CanAsk)
        {
            vm.SetStatus("No LLM available for the summary", true);
            return;
        }
        if (vm.WritingSummary.Trim().Length > 0
            && !await Dialogs.Confirm("Generate the summary", "The summary below will be replaced by a new one. Go on?", "Generate"))
            return;
        var model = vm.Assistant.CurrentModelName ?? "LLM";
        vm.IsBusy = true;
        try
        {
            var (_, error) = await AssistWindows.AskAsync("Summary", $"{model} reads the chapters and writes the summary of the writing…",
                async token =>
                {
                    await vm.GenerateSummaryAsync(token);
                    return vm.WritingSummary;
                }, "Summary", "GhostWriter");
            if (error is not null)
                vm.SetStatus("The summary was not generated: " + error, true);
        }
        finally
        {
            vm.IsBusy = false;
        }
    }

