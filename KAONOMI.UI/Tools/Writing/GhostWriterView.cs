    /// <summary>
    /// The 🎤 of the dictation: held, the microphone records (the button turns red) and the words said so far are given to
    /// <paramref name="show"/> as they come (final: false, each time all of them); released, the speech is turned into text
    /// (Whisper, in the language of the voice input of the chat) and given once more (final: true, empty when nothing was
    /// heard).
    /// </summary>
    internal static Button Mic(GhostWriterWindowViewModel vm, Action<string, bool> show)
    {
        var mic = new Button { Content = "🎤", FontSize = 11, Padding = new Thickness(5, 0), MinHeight = 0, Focusable = false, VerticalAlignment = VerticalAlignment.Center };
        ToolTip.SetTip(mic, "Hold to dictate (the words show as you speak), release: they are written at the caret");
        var normal = mic.Background;
        // True while this 🎤 records (its release, or the end of its control, stops it).
        var holding = false;
        async Task Release()
        {
            if (!holding)
                return;
            holding = false;
            mic.Background = normal;
            try
            {
                var text = await vm.StopDictationAsync();
                show(text, true);
            }
            catch (Exception ex)
            {
                vm.SetStatus("Dictation: " + ex.Message, true);
                ActivityLog.Error("GhostWriter", "Dictation stop failed", ex);
            }
        }
        mic.AddHandler(InputElement.PointerPressedEvent, (_, e) =>
        {
            if (!e.GetCurrentPoint(mic).Properties.IsLeftButtonPressed)
                return;
            // A dictation left on (its release was never seen): this press ends it.
            if (vm.IsDictating)
            {
                holding = true;
                _ = Release();
                return;
            }
            vm.StartDictation(text => Ui.OnMain(() =>
            {
                if (vm.IsDictating)
                    show(text, false);
            }));
            if (vm.IsDictating)
            {
                holding = true;
                mic.Background = Ui.Red;
            }
        }, RoutingStrategies.Tunnel, handledEventsToo: true);
        mic.AddHandler(InputElement.PointerReleasedEvent, (_, _) => _ = Release(), RoutingStrategies.Tunnel, handledEventsToo: true);
        mic.PointerCaptureLost += (_, _) => _ = Release();
        // The control goes (the tab rebuilt, the window closed) while it records: the microphone is closed.
        mic.DetachedFromVisualTree += (_, _) => _ = Release();
        WritingUi.Enabled(mic, vm, nameof(vm.IsTranscribing), invert: true);
        return mic;
    }

    /// <summary>
    /// The dictation into <paramref name="edit"/>: the words said so far typed at the caret (a space before them when they
    /// follow a word; after them with <paramref name="spaceAfter"/>), replaced by the next ones as they come, then by the
    /// final text (removed when it is empty).
    /// </summary>
    internal static Action<string, bool> Dictation(TextBox edit, bool spaceAfter)
    {
        // Where the words of the dictation in progress are; null: none shown.
        (int Start, int Length)? shown = null;
        var space = string.Empty;
        return (text, final) =>
        {
            var current = edit.Text ?? string.Empty;
            int at;
            if (shown is { } range && range.Start + range.Length <= current.Length)
            {
                current = current.Remove(range.Start, range.Length);
                at = range.Start;
            }
            else
            {
                at = Math.Clamp(edit.CaretIndex, 0, current.Length);
                space = at > 0 && !char.IsWhiteSpace(current[at - 1]) ? " " : "";
            }
            shown = null;
            if (text.Length == 0)
            {
                edit.Text = current;
                edit.CaretIndex = at;
                return;
            }
            var inserted = space + text + (spaceAfter ? " " : "");
            edit.Text = current.Insert(at, inserted);
            edit.CaretIndex = at + inserted.Length;
            if (!final)
                shown = (at, inserted.Length);
        };
    }

