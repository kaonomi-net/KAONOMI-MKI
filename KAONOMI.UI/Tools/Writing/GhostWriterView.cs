    /// <summary>
    /// The list of <paramref name="items"/> on the left (each row its label, kept up to date when <paramref name="labelProperty"/>
    /// of the item changes, a muted detail under it), its buttons above it, the editor of the item selected on the right. A
    /// double-click on a row calls <paramref name="activate"/> when given.
    /// </summary>
    private static Control Master<T>(GhostWriterWindowViewModel vm, ObservableCollection<T> items, string selectedProperty,
        Func<T, string> label, string labelProperty, Func<T, string> detail, Func<T?> selected, Action<T> select, string empty,
        Control[] buttons, Control editor, Action<T>? activate) where T : class, INotifyPropertyChanged
    {
        var list = new StackPanel { Margin = new Thickness(0, 0, 8, 0) };
        var none = WritingUi.Placeholder(empty);
        none.VerticalAlignment = VerticalAlignment.Top;
        WritingUi.Items(list, items, item =>
        {
            var title = Ui.Label(string.Empty, Ui.TextBright, 13);
            var info = Ui.Label(string.Empty, Ui.Muted, 10);
            var content = Ui.Column(1, title, info);
            // Every field of the item may change the label or the detail (the title, the position, the text).
            Ui.When(content, item, () =>
            {
                title.Text = label(item);
                info.Text = detail(item);
            }, labelProperty, "Position", "Text", "IsMainCharacter", "Disqualified", "GeoLocation");
            var row = WritingUi.ResultRow(vm, selectedProperty, () => ReferenceEquals(selected(), item), () => select(item), content, 46);
            if (activate is not null)
            {
                ToolTip.SetTip(row, "Double-click: write the chapter");
                WritingUi.OnDoubleClick(row, () => activate(item));
            }
            return row;
        }, none);

        var buttonRow = WritingUi.Flow(6, buttons);
        buttonRow.Margin = new Thickness(0, 0, 0, 8);
        var left = WritingUi.Page([buttonRow], new Panel { Children = { Ui.Scroll(list), none } });
        return WritingUi.SplitH(left, editor, 340, minLeft: 260);
    }

