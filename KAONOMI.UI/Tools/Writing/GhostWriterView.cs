/// <summary>
/// /write: the ghost writer, opened at full size. Header: the title of the writing, NEW, ☁ SAVE, AUTOSAVE (every minute while
/// it has changes). Six tabs: GENERAL (title, author, style, description, goals, audience, and the writings of the search
/// engine), ACTORS, LOCATIONS and CHAPTERS (a list on the left, the fields of the one selected on the right), PUBLISH (the
/// summary, generated by the model of the chat, and the exports: MS Word, PDF, HTML, Blogger) and JOURNAL (every action that
/// changed the text, read-only). A double-click on a chapter (or ✍ WRITE) opens its own window, where its text is written
/// (<see cref="ChapterTextView"/>). The 🎤 beside a caption dictates into its field while it is held.
/// </summary>
[ToolView(typeof(GhostWriterWindowViewModel), "Ghost writer", "✍", 1400, 900)]
public sealed class GhostWriterView : IToolView
{
    public Control Build(object viewModel, Shell shell)
    {
        var vm = (GhostWriterWindowViewModel)viewModel;
        void Write(WriterChapter chapter) => OpenChapter(shell, vm, chapter);
        vm.ConfirmAsync = WritingUi.Confirm;

        // ── The header ──
        var name = Ui.Label(string.Empty, Ui.Muted, 11);
        name.Margin = new Thickness(10, 0);
        Ui.When(name, vm, () => name.Text = (vm.Title.Trim().Length > 0 ? vm.Title.Trim() : "Untitled writing") + (vm.IsDirty ? " •" : ""),
            nameof(vm.Title), nameof(vm.IsDirty));
        var autoSave = Ui.Check("AUTOSAVE", vm, nameof(vm.AutoSave));
        ToolTip.SetTip(autoSave, "Save the writing in the search engine every minute while it has changes");
        var actions = Ui.Row(8,
            Ui.Button("✚ NEW", () => _ = NewAsync(vm), "A new, empty writing (the changes not saved are asked about)"),
            WritingUi.Command("☁ SAVE", vm.SaveToServerCommand, primary: true, tooltip: "Save the writing in the search engine: a new document the first time (its id the slug of the title), a new version after"),
            autoSave);
        var header = WritingUi.Toolbar(Ui.Dock((Ui.Label("GHOST WRITER", Ui.TextBright, 14, bold: true), Dock.Left), (actions, Dock.Right), (name, Dock.Left)));

        // ── The tabs ──
        var tabs = new TabControl();
        TabItem AddTab(string title, Control content)
        {
            var item = new TabItem { Header = title, Content = WritingUi.Margin(content, 10) };
            tabs.Items.Add(item);
            return item;
        }
        AddTab("📖 GENERAL", BuildGeneral(vm));
        AddTab("🎭 ACTORS", BuildActors(vm));
        AddTab("🗺 LOCATIONS", BuildLocations(vm));
        AddTab("📑 CHAPTERS", BuildChapters(vm, Write));
        AddTab("🚀 PUBLISH", BuildPublish(vm));
        var journalTab = AddTab("📜 JOURNAL", BuildJournal(vm));
        // The journal read again when its tab shows, and when an entry of this writing arrives while it shows.
        tabs.SelectionChanged += (_, e) =>
        {
            if (ReferenceEquals(e.Source, tabs) && ReferenceEquals(tabs.SelectedItem, journalTab))
                Ui.Run(vm.RefreshJournalCommand);
        };
        void JournalAdded(WriterJournalEntry entry) => Ui.OnMain(() =>
        {
            if (ReferenceEquals(tabs.SelectedItem, journalTab) && entry.WritingId == vm.JournalWritingId)
                Ui.Run(vm.RefreshJournalCommand);
        });

        var summary = Ui.Bound(vm, nameof(vm.Summary), Ui.Muted, 11);
        var status = WritingUi.StatusBar(vm, nameof(vm.Status), nameof(vm.IsError), nameof(vm.IsBusy), extra: summary);
        var root = WritingUi.Page([header], WritingUi.Margin(tabs, 8), status);

        // AUTOSAVE: every minute, the writing is saved when the box is ticked and it has changes.
        var timer = new DispatcherTimer { Interval = TimeSpan.FromSeconds(60) };
        timer.Tick += (_, _) => vm.AutoSaveTick();

        // The text windows of the chapters close when the chapters are replaced (a new writing, another one opened).
        void CloseChapters() => Ui.OnMain(() =>
        {
            foreach (var window in shell.Deck.Windows.Where(w => w.Key.StartsWith(ChapterTextWindowViewModel.KeyPrefix, StringComparison.Ordinal)).ToList())
                if (window.ViewModel is ChapterTextWindowViewModel text && ReferenceEquals(text.Writing, vm))
                    shell.Deck.Close(window);
        });
        // A chapter removed: its text window closes (what would be typed there would go nowhere).
        void CloseChapter(WriterChapter chapter) => Ui.OnMain(() =>
        {
            if (shell.Deck.Find(ChapterTextWindowViewModel.KeyOf(chapter)) is { ViewModel: ChapterTextWindowViewModel text } window
                && ReferenceEquals(text.Chapter, chapter))
                shell.Deck.Close(window);
        });

        void UpdateTitle() =>
            WritingUi.SetTitle(root, "Ghost writer · " + (vm.Title.Trim().Length > 0 ? vm.Title.Trim() : "Untitled writing") + (vm.IsDirty ? " •" : ""));
        Ui.When(root, vm, UpdateTitle, nameof(vm.Title), nameof(vm.IsDirty));

        // Once in its window: the events of the view model, opened at full size, a draft left offered back; the window
        // closed: everything undone, the chapter windows closed.
        var started = false;
        root.AttachedToVisualTree += (_, _) =>
        {
            timer.Start();
            if (started)
                return;
            started = true;
            vm.ChaptersReplaced += CloseChapters;
            vm.ChapterRemoved += CloseChapter;
            WriterJournal.Added += JournalAdded;
            WritingUi.Later(() =>
            {
                UpdateTitle();
                if (WritingUi.WindowOf(root) is not { } window)
                    return;
                window.Closed += () =>
                {
                    timer.Stop();
                    vm.ChaptersReplaced -= CloseChapters;
                    vm.ChapterRemoved -= CloseChapter;
                    WriterJournal.Added -= JournalAdded;
                    CloseChapters();
                };
                if (!window.IsMaximized)
                    shell.Deck.ToggleMaximize(window);
                // A draft left by a window closed (or a chat stopped) with changes not saved: offered back.
                _ = vm.OfferDraftAsync();
            });
        };
        root.DetachedFromVisualTree += (_, _) => timer.Stop();
        return root;
    }

