    /// <summary>
    /// The picture of the actor (a portrait), with 📂 UPLOAD (a file copied into Pictures/kaonomi/writer/&lt;title&gt;),
    /// 🎨 GENERATE (a prompt drawn by Fooocus, kept there too) and ✕ (no picture; the file stays). A double-click opens it.
    /// </summary>
    private static Control ActorPicture(GhostWriterWindowViewModel vm, WriterActor a)
    {
        var image = new Image { Stretch = Stretch.Uniform };
        var empty = WritingUi.Placeholder("No picture yet:\n📂 upload one, or 🎨 generate it with Fooocus");
        var frame = Ui.Box(new Panel { Children = { empty, image } }, 6, Ui.Field);
        frame.Width = 240;
        frame.Height = 320;
        ToolTip.SetTip(frame, "Double-click: open the picture");
        WritingUi.OnDoubleClick(frame, () =>
        {
            if (File.Exists(a.ImagePath))
                PictureLibrary.OpenWithSystem(a.ImagePath);
        });
        async void Show()
        {
            var path = a.ImagePath;
            Bitmap? bitmap = null;
            try
            {
                bitmap = File.Exists(path) ? await PictureLibrary.DecodeAsync(path, 800, CancellationToken.None) : null;
            }
            catch (Exception ex) when (ex is IOException or InvalidOperationException or UnauthorizedAccessException or ArgumentException)
            {
                ActivityLog.Error("GhostWriter", $"Picture of {a.Name} not read: {path}", ex);
            }
            if (path != a.ImagePath)
            {
                bitmap?.Dispose();
                return;
            }
            var old = image.Source as IDisposable;
            image.Source = bitmap;
            old?.Dispose();
            empty.IsVisible = bitmap is null;
        }
        Ui.When(image, a, Show, nameof(a.ImagePath));

        async Task UploadAsync()
        {
            var file = await Dialogs.OpenFile($"Picture of {a.Name}", WritingUi.PictureFilters, ChatSettings.SystemPicturesDirectory);
            if (file is not null)
                vm.SetActorPicture(a, file);
        }
        async Task GenerateAsync()
        {
            var prompt = await Dialogs.Ask($"Portrait of {a.Name}", "Describe the picture for Fooocus (in English is best):", vm.ActorPrompt(a), multiline: true);
            if (!string.IsNullOrWhiteSpace(prompt))
                await vm.GenerateActorPictureAsync(a, prompt);
        }
        var upload = Ui.Button("📂 UPLOAD", () => _ = UploadAsync(), "Pick a picture: it is copied into Pictures/kaonomi/writer/<title>");
        var generate = WritingUi.Enabled(Ui.Button("🎨 GENERATE", () => _ = GenerateAsync(), "Describe the portrait: Fooocus draws it, kept in Pictures/kaonomi/writer/<title>"),
            vm, nameof(vm.IsBusy), invert: true);
        var clear = Ui.Button("✕", () => a.ImagePath = string.Empty, "No picture for this actor (the file is kept)");
        return Ui.Column(8, frame, Ui.Row(6, upload, generate, clear));
    }

