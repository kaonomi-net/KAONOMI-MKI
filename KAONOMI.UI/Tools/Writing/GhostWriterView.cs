    private static Control ChapterEditor(GhostWriterWindowViewModel vm, WriterChapter c, Action<WriterChapter> write)
    {
        var words = Ui.Label(string.Empty, Ui.Muted, 11);
        // The text as it reads (Markdown rendered), the words of a footnote followed by its number in superscript; built
        // again a moment after the text changes (it is typed in the window of the chapter).
        var preview = new ContentControl();
        var refresh = new DispatcherTimer { Interval = TimeSpan.FromMilliseconds(400) };
        void Render()
        {
            refresh.Stop();
            words.Text = $"{GhostWriterWindowViewModel.Words(c.Text)} word(s) written";
            preview.Content = MarkdownView.Build(c.Text.Trim().Length > 0
                ? WithFootnoteMarks(c.Text.Trim())
                : "*Nothing written yet: double-click the chapter in the list, or ✍ WRITE.*");
        }
        refresh.Tick += (_, _) => Render();
        Render();
        void Changed(object? sender, PropertyChangedEventArgs e)
        {
            if (e.PropertyName == nameof(c.Text))
                Ui.OnMain(() =>
                {
                    refresh.Stop();
                    refresh.Start();
                });
        }
        c.PropertyChanged += Changed;
        preview.DetachedFromVisualTree += (_, _) =>
        {
            c.PropertyChanged -= Changed;
            refresh.Stop();
        };
        preview.AttachedToVisualTree += (_, _) =>
        {
            c.PropertyChanged -= Changed;
            c.PropertyChanged += Changed;
            Render();
        };

        var writeButton = Ui.Button("✍ WRITE", () => write(c), "Open the window where the chapter is written (or double-click it in the list)", primary: true);
        writeButton.VerticalAlignment = VerticalAlignment.Bottom;
        writeButton.Margin = new Thickness(8, 0, 0, 0);
        var title = WritingUi.Field("Title", WritingUi.Line(c, nameof(c.Title), "The title of the chapter"));
        return Ui.Scroll(WritingUi.Margin(Ui.Column(10,
            Ui.Dock((writeButton, Dock.Right), (title, Dock.Left)),
            Area(vm, "Description", WritingUi.Lines(c, nameof(c.Description), 100, "What happens in the chapter")),
            WritingUi.Cells(2,
                Area(vm, "Perception goal", WritingUi.Lines(c, nameof(c.PerceptionGoal), 80, "What the reader should feel or understand")),
                Area(vm, "Ambiance", WritingUi.Lines(c, nameof(c.Ambiance), 80, "Light, weather, rhythm, music of the chapter"))),
            WritingUi.Separator(),
            Ui.Row(8, Ui.Caption("Text", Ui.Accent, 11), words),
            preview,
            FootnotesOf(c, () => write(c), WritingUi.OpenWeb)), 10, 0, 12, 10));
    }

    private const string Superscripts = "⁰¹²³⁴⁵⁶⁷⁸⁹";

    /// <summary>A number in superscript digits (¹, ²³…).</summary>
    internal static string Superscript(int number) =>
        new(number.ToString(System.Globalization.CultureInfo.InvariantCulture).Select(d => Superscripts[d - '0']).ToArray());

    /// <summary><paramref name="markdown"/> with each footnote link <c>[words](note:N)</c> turned into the words followed by N in superscript.</summary>
    private static string WithFootnoteMarks(string markdown) =>
        Regex.Replace(markdown,
            @"\[(?<words>(?:[^\[\]]|\[[^\]]*\])*)\]\(<?" + Regex.Escape(WriterChapter.NoteScheme) + @"(?<number>\d+)>?\)",
            m => m.Groups["words"].Value + Superscript(int.Parse(m.Groups["number"].Value, System.Globalization.CultureInfo.InvariantCulture)));

    /// <summary>
    /// The footnotes of chapter <paramref name="c"/> (hidden while there is none): the number in superscript, the words, the
    /// text of the note and its links (a click opens one with <paramref name="openLink"/>); a click on a note calls
    /// <paramref name="openNote"/> with it.
    /// </summary>
    internal static Control FootnotesOf(WriterChapter c, Action openNote, Action<string> openLink, Action<WriterFootnote>? editNote = null)
    {
        var list = new StackPanel { Spacing = 4 };
        WritingUi.Items(list, c.Footnotes, note =>
        {
            var text = WritingUi.Clamp(Ui.Label(string.Empty, Ui.Text, 12), 1);
            var main = new Button
            {
                Content = text,
                Background = Brushes.Transparent,
                BorderThickness = new Thickness(0),
                HorizontalContentAlignment = HorizontalAlignment.Left,
                Cursor = new Cursor(StandardCursorType.Hand)
            };
            main.Click += (_, _) =>
            {
                if (editNote is not null)
                    editNote(note);
                else
                    openNote();
            };
            var linkRow = Ui.Row(4);
            linkRow.Margin = new Thickness(6, 0, 0, 0);
            var row = Ui.Dock((linkRow, Dock.Right), (main, Dock.Left));
            void Refresh()
            {
                text.Text = $"{Superscript(note.Number)} « {note.Anchor} » — {(note.Text.Length > 0 ? note.Text : "(no text yet)")}";
                ToolTip.SetTip(main, $"Footnote {note.Number} on « {note.Anchor} »\n{note.Text}\n({(editNote is null ? "click: open the chapter to edit it" : "click: edit it")})");
                linkRow.Children.Clear();
                foreach (var link in note.Links)
                {
                    var address = link.Url;
                    var button = Ui.Button("🔗 " + (link.Title.Length > 0 ? link.Title : address), () => openLink(address), address);
                    button.FontSize = 11;
                    linkRow.Children.Add(button);
                }
            }
            Ui.When(row, note, Refresh, nameof(note.Number), nameof(note.Anchor), nameof(note.Text), nameof(note.Links));
            return row;
        });
        var box = Ui.Column(4, WritingUi.Separator(), Ui.Caption("Footnotes", Ui.Accent, 11), list);
        void Show() => Ui.OnMain(() => box.IsVisible = c.Footnotes.Count > 0);
        System.Collections.Specialized.NotifyCollectionChangedEventHandler changed = (_, _) => Show();
        c.Footnotes.CollectionChanged += changed;
        box.DetachedFromVisualTree += (_, _) => c.Footnotes.CollectionChanged -= changed;
        box.AttachedToVisualTree += (_, _) =>
        {
            c.Footnotes.CollectionChanged -= changed;
            c.Footnotes.CollectionChanged += changed;
            Show();
        };
        Show();
        return box;
    }

