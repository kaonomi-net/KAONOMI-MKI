/// <summary>
/// The windows of the help of the model of the chat for the writing tools (the WorkWindows of the Godot chat): the waiting
/// dialog of a question (what is done, the time elapsed, Cancel), the evaluation (Markdown), the result of a translation or a
/// rewriting (editable, Replace / Insert below), the code window (typed, or generated by the LLM) and the image window
/// (Fooocus).
/// </summary>
public static class AssistWindows
{
    private static int _next;

    private static DeskWindow Open(Shell shell, string title, string icon, Control content, Size size) =>
        shell.OpenControl($"writing-assist#{Interlocked.Increment(ref _next)}", title, icon, content, size);

    private static TextBlock Heading(string text) => Ui.Label(text, Ui.TextBright, 18, wrap: true, bold: true);

    private static Border Quote(string text, IBrush color, bool mono)
    {
        var shown = text.Length > 600 ? text[..600] + "…" : text;
        var label = new SelectableTextBlock { Text = shown, Foreground = color, FontSize = 12, TextWrapping = TextWrapping.Wrap, MaxLines = 6, TextTrimming = TextTrimming.CharacterEllipsis };
        if (mono)
            label.FontFamily = Ui.Mono;
        return new Border { Child = label, BorderBrush = color, BorderThickness = new Thickness(2, 0, 0, 0), Padding = new Thickness(8, 2) };
    }

    // ── Waiting ──

    /// <summary>
    /// Runs <paramref name="ask"/> with the waiting dialog (Cancel, ten minutes at most): its answer, or the error; both null
    /// when it was cancelled.
    /// </summary>
    public static async Task<(string? Answer, string? Error)> AskAsync(string heading, string message,
        Func<CancellationToken, Task<string>> ask, string what, string category = "Writing")
    {
        using var cancel = new CancellationTokenSource(TimeSpan.FromMinutes(10));
        var busy = BusyDialog.Show(heading, message, cancel);
        try
        {
            return (await ask(cancel.Token), null);
        }
        catch (OperationCanceledException) when (busy.IsCancelledByUser)
        {
            return (null, null);
        }
        catch (Exception ex) when (ex is System.Net.Http.HttpRequestException or InvalidOperationException
                                       or OperationCanceledException or System.Text.Json.JsonException)
        {
            ActivityLog.Error(category, $"{what} failed", ex);
            return (null, ex is OperationCanceledException ? "no answer after 10 minutes" : ex.Message);
        }
        finally
        {
            busy.Finish();
        }
    }

    /// <summary>The waiting dialog: the heading, what is done (can change), the time elapsed, Cancel.</summary>
    public sealed class BusyDialog
    {
        private readonly Window _window;
        private readonly TextBlock _message;
        private readonly DispatcherTimer _clock;
        private bool _done;

        private BusyDialog(string heading, string message, CancellationTokenSource cancel)
        {
            var started = Stopwatch.StartNew();
            _message = Ui.Label(message, Ui.Text, 13, wrap: true);
            var elapsed = Ui.Label("0:00", Ui.Muted, 11);
            var progress = new ProgressBar { IsIndeterminate = true, Height = 4, MinHeight = 4 };
            var stop = Ui.Button("CANCEL", () =>
            {
                IsCancelledByUser = true;
                cancel.Cancel();
                Finish();
            });
            stop.IsCancel = true;
            stop.HorizontalAlignment = HorizontalAlignment.Right;
            _window = new Window
            {
                Title = heading,
                Width = 440,
                SizeToContent = SizeToContent.Height,
                CanResize = false,
                ShowInTaskbar = false,
                WindowStartupLocation = WindowStartupLocation.CenterOwner,
                Content = new Border { Padding = new Thickness(18), Child = Ui.Column(12, Ui.Label(heading, Ui.TextBright, 15, bold: true), _message, progress, Ui.Dock((stop, Dock.Right), (elapsed, Dock.Left))) }
            };
            _window.Closing += (_, _) =>
            {
                if (!_done)
                {
                    IsCancelledByUser = true;
                    cancel.Cancel();
                }
            };
            _clock = new DispatcherTimer { Interval = TimeSpan.FromSeconds(1) };
            _clock.Tick += (_, _) => elapsed.Text = started.Elapsed.ToString(@"m\:ss");
            _clock.Start();
            if (Dialogs.Owner is { IsVisible: true } owner)
                _ = _window.ShowDialog(owner);
            else
                _window.Show();
        }

        public bool IsCancelledByUser { get; private set; }

        public string Message
        {
            set => Ui.OnMain(() => _message.Text = value);
        }

        public static BusyDialog Show(string heading, string message, CancellationTokenSource cancel) => new(heading, message, cancel);

        public void Finish() => Ui.OnMain(() =>
        {
            if (_done)
                return;
            _done = true;
            _clock.Stop();
            _window.Close();
        });
    }

    // ── Results ──

    /// <summary>
    /// The result of 🧐 Evaluate or 🧪 AI-Check: the text evaluated, then the analysis of the LLM (Markdown) or the error,
    /// Copy and Close; <paramref name="actionLabel"/> offers an action on the result (it closes the window, then runs).
    /// </summary>
    public static void Evaluation(Shell shell, string text, string model, string? markdown, string? error,
        string heading = "🧐 Evaluation", string? subtitle = null, string? actionLabel = null, Action? action = null)
    {
        var plain = new string(heading.SkipWhile(c => !char.IsLetter(c)).ToArray());
        Control result = error is null
            ? MarkdownView.Build(markdown ?? string.Empty)
            : Ui.Label($"{plain} failed: {error}", Ui.Red, 13, wrap: true);
        var status = Ui.Label(string.Empty, Ui.Muted, 11);
        Control? page = null;
        var copy = Ui.Button("COPY", () =>
        {
            Dialogs.Copy(markdown ?? string.Empty);
            status.Text = "✓ Copied";
        });
        copy.IsEnabled = error is null;
        var close = Ui.Button("CLOSE", () => shell.Close(page!), primary: action is null || error is not null);
        var buttons = Ui.Row(8, status, copy);
        if (actionLabel is not null && action is not null && error is null)
            buttons.Children.Add(Ui.Button(actionLabel, () =>
            {
                shell.Close(page!);
                action();
            }, primary: true));
        buttons.Children.Add(close);
        buttons.HorizontalAlignment = HorizontalAlignment.Right;
        var header = Ui.Column(6,
            Heading(heading),
            Ui.Label(subtitle ?? $"Mathematical and formal criticism, then ideas to improve the text, without the solution · {model}", Ui.Muted, 11, wrap: true),
            Quote(text, WritingUi.Amber, mono: true));
        page = WritingUi.Margin(WritingUi.Page([header, WritingUi.Separator()], Ui.Scroll(WritingUi.Margin(result, 0, 6, 10, 6)), buttons), 18);
        Open(shell, plain, heading.Split(' ')[0], page, new Size(680, 620));
    }

    /// <summary>
    /// The result of 🌐 Translate, ✏️ Correct the spelling or ✨ Rewrite: the text, the result (which can be changed),
    /// Replace, Insert below, Copy, Close. <paramref name="replace"/> and <paramref name="insert"/> return false when the
    /// text changed meanwhile.
    /// </summary>
    public static void Translation(Shell shell, string text, string language, string model, string? translation, string? error,
        Func<string, bool> replace, Func<string, bool> insert, string? heading = null, string? title = null,
        string replaceLabel = "REPLACE THE SELECTION", string insertLabel = "INSERT BELOW")
    {
        var result = new TextBox
        {
            Text = translation ?? $"{title ?? "The translation"} failed: {error}",
            AcceptsReturn = true,
            TextWrapping = TextWrapping.Wrap,
            IsReadOnly = error is not null,
            FontSize = 14,
            MinHeight = 160,
            VerticalContentAlignment = VerticalAlignment.Top
        };
        var status = Ui.Label(string.Empty, Ui.Muted, 11, wrap: true);
        Control? page = null;
        void Put(Func<string, bool> action)
        {
            if (action(result.Text ?? string.Empty))
                shell.Close(page!);
            else
                status.Text = "The text changed since the selection: copy the text instead.";
        }
        var replaceButton = Ui.Button(replaceLabel, () => Put(replace), "The text takes the place of the selected text (Ctrl / ⌘ + Z undoes it)", primary: true);
        var insertButton = Ui.Button(insertLabel, () => Put(insert), "The text is added under the selected text, which is kept");
        var copy = Ui.Button("COPY", () =>
        {
            Dialogs.Copy(result.Text ?? string.Empty);
            status.Text = "✓ Copied";
        });
        replaceButton.IsEnabled = insertButton.IsEnabled = copy.IsEnabled = error is null;
        var close = Ui.Button("CLOSE", () => shell.Close(page!));
        var header = Ui.Column(6,
            Heading(heading ?? $"🌐 Translation into {language}"),
            Ui.Label(model, Ui.Muted, 11),
            Quote(text, Ui.Muted, mono: false));
        var buttons = Ui.Row(8, replaceButton, insertButton, copy, close);
        page = WritingUi.Margin(WritingUi.Page([header], WritingUi.Margin(result, 0, 10, 0, 10), Ui.Dock((buttons, Dock.Right), (status, Dock.Left))), 18);
        Open(shell, title ?? $"Translation · {language}", heading?.Split(' ')[0] ?? "🌐", page, new Size(640, 520));
        WritingUi.FocusWhenShown(replaceButton);
    }

    private const string PlainText = "text";

    /// <summary>
    /// The code window: its language and its code; <paramref name="done"/> gets the language and the code on
    /// <paramref name="action"/>. With <paramref name="generate"/>, a prompt and ✨ Generate (Ctrl / ⌘ + Enter) ask the LLM,
    /// the code written can be changed before it is inserted.
    /// </summary>
    public static void Code(Shell shell, string title, string action, string language, string code, Action<string, string> done,
        Func<string, string, CancellationToken, Task<(string Language, string Code)>>? generate = null)
    {
        var languages = new List<string> { PlainText };
        languages.AddRange(CodeHighlighter.Languages);
        if (generate is not null)
            languages.Insert(0, "auto");
        var current = string.IsNullOrEmpty(language) ? (generate is null ? PlainText : "auto") : CodeHighlighter.Normalize(language);
        if (!languages.Contains(current))
            languages.Insert(1, current);
        var languageBox = new ComboBox { MinWidth = 180, ItemsSource = languages, SelectedItem = current };
        string Selected() => languageBox.SelectedItem as string ?? PlainText;
        string LanguageChosen() => Selected() is var l && l is not PlainText and not "auto" ? l : string.Empty;

        var codeBox = new TextBox
        {
            Text = code,
            PlaceholderText = generate is null ? "Type or paste the code" : "The generated code shows here; it can be changed before it is inserted",
            AcceptsReturn = true,
            AcceptsTab = true,
            FontFamily = Ui.Mono,
            FontSize = 13,
            MinHeight = 200,
            TextWrapping = TextWrapping.NoWrap,
            VerticalContentAlignment = VerticalAlignment.Top
        };
        var status = Ui.Label(string.Empty, Ui.Muted, 11, wrap: true);
        Control? page = null;
        var ok = Ui.Button(action.ToUpperInvariant(), () =>
        {
            done(LanguageChosen(), (codeBox.Text ?? string.Empty).Replace("\r\n", "\n").TrimEnd());
            shell.Close(page!);
        }, primary: generate is null);
        ok.IsEnabled = code.Trim().Length > 0;
        codeBox.TextChanged += (_, _) => ok.IsEnabled = (codeBox.Text ?? string.Empty).Trim().Length > 0;
        var cancel = Ui.Button("CANCEL", () => shell.Close(page!));

        var top = Ui.Column(8);
        CancellationTokenSource? running = null;
        if (generate is not null)
        {
            var prompt = new TextBox
            {
                AcceptsReturn = true,
                TextWrapping = TextWrapping.Wrap,
                MinHeight = 80,
                PlaceholderText = "Describe the code to generate, e.g. \"a Python function that returns the area of a circle, with a test\""
            };
            Button? run = null;
            async void Generate()
            {
                if (string.IsNullOrWhiteSpace(prompt.Text) || running is not null)
                    return;
                running = new CancellationTokenSource(TimeSpan.FromMinutes(10));
                run!.IsEnabled = false;
                status.Text = "✨ The LLM is writing the code…";
                try
                {
                    var (written, generated) = await generate(prompt.Text.Trim(), Selected(), running.Token);
                    var id = string.IsNullOrEmpty(written) ? PlainText : CodeHighlighter.Normalize(written);
                    if (!languages.Contains(id))
                    {
                        languages.Insert(1, id);
                        languageBox.ItemsSource = languages.ToList();
                    }
                    languageBox.SelectedItem = id;
                    codeBox.Text = generated;
                    status.Text = "✓ Code written: change it if needed, then Insert";
                    ok.Classes.Add("primary");
                }
                catch (Exception ex) when (ex is OperationCanceledException or System.Net.Http.HttpRequestException or InvalidOperationException or System.Text.Json.JsonException)
                {
                    status.Text = ex is OperationCanceledException ? "No answer after 10 minutes." : $"Not generated: {ex.Message}";
                }
                finally
                {
                    running?.Dispose();
                    running = null;
                    run.IsEnabled = true;
                }
            }
            run = Ui.Button("✨ GENERATE", Generate, "Ask the LLM to write the code (Ctrl / ⌘ + Enter)", primary: true);
            run.VerticalAlignment = VerticalAlignment.Bottom;
            run.Margin = new Thickness(8, 0, 0, 0);
            prompt.KeyDown += (_, e) =>
            {
                if (e.Key == Key.Enter && WritingUi.HasCommandKey(e))
                {
                    e.Handled = true;
                    Generate();
                }
            };
            top.Children.Add(Ui.Caption("Prompt"));
            top.Children.Add(Ui.Dock((run, Dock.Right), (prompt, Dock.Left)));
            WritingUi.FocusWhenShown(prompt);
        }
        else
            WritingUi.FocusWhenShown(codeBox);
        top.Children.Add(Ui.Row(8, Ui.Caption("Language"), languageBox));
        top.Margin = new Thickness(0, 0, 0, 10);

        var buttons = Ui.Row(8, ok, cancel);
        buttons.Margin = new Thickness(0, 10, 0, 0);
        page = WritingUi.Margin(WritingUi.Page([top], codeBox, Ui.Dock((buttons, Dock.Right), (status, Dock.Left))), 16);
        var window = Open(shell, title, "</>", page, new Size(820, generate is null ? 600 : 700));
        window.Closed += () => running?.Cancel();
    }

    /// <summary>Sizes offered by the image window, width*height (the ones of SDXL).</summary>
    private static readonly string[] ImageSizes = ["1152*896", "1024*1024", "896*1152", "1344*768", "768*1344", "1216*832", "832*1216"];

    /// <summary>Performances of Fooocus; the fast ones download a LoRA the first time.</summary>
    private static readonly string[] Performances = ["Speed", "Quality", "Extreme Speed", "Lightning", "Hyper-SD"];

    /// <summary>
    /// The ✨🖼 window: a prompt, the size, the performance; ✨ Generate asks Fooocus and shows the image (generated again until
    /// it fits); Insert gives its path to <paramref name="done"/>. The images generated but not inserted are deleted when the
    /// window closes.
    /// </summary>
    public static void ImageGeneration(Shell shell, string title, Func<string, string, string, CancellationToken, Task<string>> generate, Action<string> done)
    {
        var prompt = new TextBox
        {
            AcceptsReturn = true,
            TextWrapping = TextWrapping.Wrap,
            MinHeight = 84,
            PlaceholderText = "Describe the image, in English, e.g. \"a clean diagram of a right triangle with its angles, white background, flat style\""
        };
        var size = new ComboBox { ItemsSource = ImageSizes, SelectedIndex = 0, MinWidth = 140 };
        var performance = new ComboBox { ItemsSource = Performances, SelectedIndex = 0, MinWidth = 150 };
        ToolTip.SetTip(performance, "Speed: about a minute; Quality: twice as long; Extreme Speed, Lightning, Hyper-SD: a few seconds");
        var picture = new Image { Stretch = Stretch.Uniform };
        var placeholder = WritingUi.Placeholder("The image shows here; generate it again until it fits, then Insert");
        var frame = Ui.Box(new Panel { Children = { placeholder, picture } }, 6, Ui.Field);
        var status = Ui.Label(string.Empty, Ui.Muted, 11, wrap: true);
        var progress = new ProgressBar { IsIndeterminate = true, IsVisible = false, Height = 4, MinHeight = 4 };

        string? path = null;
        string? inserted = null;
        var generated = new List<string>();
        CancellationTokenSource? running = null;
        Control? page = null;
        var insert = Ui.Button("INSERT", () =>
        {
            if (path is null)
                return;
            inserted = path;
            done(path);
            shell.Close(page!);
        });
        insert.IsEnabled = false;
        var cancel = Ui.Button("CANCEL", () => shell.Close(page!));
        Button? run = null;
        var started = new Stopwatch();
        var clock = new DispatcherTimer { Interval = TimeSpan.FromSeconds(1) };
        clock.Tick += (_, _) => status.Text = $"✨ Fooocus is drawing the image… {started.Elapsed:m\\:ss}";

        async void Generate()
        {
            if (string.IsNullOrWhiteSpace(prompt.Text) || running is not null)
                return;
            running = new CancellationTokenSource(TimeSpan.FromMinutes(30));
            run!.IsEnabled = false;
            progress.IsVisible = true;
            started.Restart();
            clock.Start();
            status.Text = "✨ Fooocus is drawing the image… 0:00";
            try
            {
                path = await generate(prompt.Text.Trim(), ImageSizes[Math.Max(0, size.SelectedIndex)], Performances[Math.Max(0, performance.SelectedIndex)], running.Token);
                generated.Add(path);
                var old = picture.Source as IDisposable;
                picture.Source = await PictureLibrary.DecodeAsync(path, 1400, CancellationToken.None);
                old?.Dispose();
                placeholder.IsVisible = picture.Source is null;
                insert.IsEnabled = true;
                insert.Classes.Add("primary");
                status.Text = $"✓ Image ready in {started.Elapsed.TotalSeconds:0} s, saved as {System.IO.Path.GetFileName(path)}: Insert it, or generate again";
            }
            catch (Exception ex) when (ex is OperationCanceledException or System.Net.Http.HttpRequestException or InvalidOperationException
                                           or System.Text.Json.JsonException or System.IO.IOException or FormatException)
            {
                status.Text = ex is OperationCanceledException ? "Stopped." : $"Not generated: {ex.Message}";
            }
            finally
            {
                running?.Dispose();
                running = null;
                clock.Stop();
                run.IsEnabled = true;
                progress.IsVisible = false;
            }
        }
        run = Ui.Button("✨ GENERATE", Generate, "Ask Fooocus for the image (Ctrl / ⌘ + Enter)", primary: true);
        run.VerticalAlignment = VerticalAlignment.Bottom;
        run.Margin = new Thickness(8, 0, 0, 0);
        prompt.KeyDown += (_, e) =>
        {
            if (e.Key == Key.Enter && WritingUi.HasCommandKey(e))
            {
                e.Handled = true;
                Generate();
            }
        };
        WritingUi.FocusWhenShown(prompt);

        var top = Ui.Column(8,
            Ui.Caption("Prompt"),
            Ui.Dock((run, Dock.Right), (prompt, Dock.Left)),
            Ui.Row(8, Ui.Caption("Size"), size, Ui.Caption("Performance"), performance),
            progress);
        top.Margin = new Thickness(0, 0, 0, 10);
        var buttons = Ui.Row(8, insert, cancel);
        buttons.Margin = new Thickness(0, 10, 0, 0);
        page = WritingUi.Margin(WritingUi.Page([top], frame, Ui.Dock((buttons, Dock.Right), (status, Dock.Left))), 16);
        var window = Open(shell, title, "🖼", page, new Size(860, 820));
        window.Closed += () =>
        {
            running?.Cancel();
            clock.Stop();
            (picture.Source as IDisposable)?.Dispose();
            foreach (var unused in generated)
                if (unused != inserted)
                    try
                    {
                        System.IO.File.Delete(unused);
                    }
                    catch (Exception ex) when (ex is System.IO.IOException or UnauthorizedAccessException)
                    {
                        ActivityLog.Error("Writing", $"Unused generated image not deleted: {unused}", ex);
                    }
        };
    }
