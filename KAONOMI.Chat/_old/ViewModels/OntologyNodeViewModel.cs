    private bool _isLoading;

    /// <summary>Wraps a saved node, or a new one when <paramref name="isNew"/> is true.</summary>
    public OntologyNodeViewModel(OntologyEntry entry, OntologyWindowViewModel owner, KaonomiAssistantService assistant, bool isNew = false)
    {
        _entry = entry;
        _owner = owner;
        _assistant = assistant;
        IsNew = isNew;
        Load(entry);

        if (isNew)
        {
            IsDirty = true;
            Status = "Unsaved new node";
        }
    }

    /// <summary>Blank node under <paramref name="parentId"/> (null for a root), created on first save.</summary>
    public static OntologyNodeViewModel CreateNew(
        string? parentId,
        OntologyWindowViewModel owner,
        KaonomiAssistantService assistant,
        string? confidentiality = null) =>
        new(new OntologyEntry
        {
            Id = Guid.NewGuid().ToString(),
            Date = DateTime.Now,
            DateCreated = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss"),
            AppName = "KAONOMI.Chat",
            MachineName = Environment.MachineName,
            UserName = Environment.UserName,
            Name = "New node",
            // A child starts at its parent's level: it can never be less confidential.
            Confidentiality = confidentiality ?? OntologyWindowViewModel.DefaultConfidentiality,
            NodeParentId = parentId ?? string.Empty
        }, owner, assistant, isNew: true);

