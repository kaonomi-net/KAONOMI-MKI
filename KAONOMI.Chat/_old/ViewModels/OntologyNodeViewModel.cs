    /// <summary>Refuses a level below the parents' one: the drop-down goes back to the minimum.</summary>
    partial void OnConfidentialityChanged(string value)
    {
        if (_isLoading || MinimumConfidentiality is not { } minimum
            || OntologyWindowViewModel.ConfidentialityRank(value) >= OntologyWindowViewModel.ConfidentialityRank(minimum))
            return;

        IsError = true;
        Status = $"{value} refused: \"{DisplayName}\" cannot be less confidential than its parent ({minimum})";
        // Posted: the drop-down is still applying the refused value.
        Avalonia.Threading.Dispatcher.UIThread.Post(() => Confidentiality = minimum);
    }

    /// <summary>
    /// Saves only the confidentiality (used when a parent is raised); pending edits of other fields are kept.
    /// An unsaved node is only updated in the editor.
    /// </summary>
    public async Task<bool> SetConfidentialityAsync(string level, CancellationToken cancellationToken = default)
    {
        if (!IsNew)
        {
            var updated = _entry.Copy();
            updated.Confidentiality = level;

            var result = await _assistant.UpdateOntologyAsync(updated, cancellationToken);
            if (!result.IsSuccess)
            {
                IsError = true;
                Status = result.Message ?? "The Kaonomi server rejected the change.";
                ActivityLog.Error("Ontology", $"Confidentiality {level} rejected for \"{DisplayName}\": {Status}");
                return false;
            }

            _entry = updated;
        }

        // Without marking the node as modified: the new level is already saved.
        var wasLoading = _isLoading;
        _isLoading = true;
        try
        {
            Confidentiality = level;
        }
        finally
        {
            _isLoading = wasLoading;
        }

        Status = $"Raised to {level} with its parent";
        return true;
    }

