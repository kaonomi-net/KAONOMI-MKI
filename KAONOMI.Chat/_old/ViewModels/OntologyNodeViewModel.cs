    private bool CanSave() => IsDirty;

    /// <summary>Creates (<c>PUT /ontology</c>) or updates (<c>POST /ontology/update</c>) the node.</summary>
    [RelayCommand(CanExecute = nameof(CanSave))]
    private async Task SaveAsync(CancellationToken cancellationToken)
    {
        // A child can never be less confidential than its parent.
        if (MinimumConfidentiality is { } minimum
            && OntologyWindowViewModel.ConfidentialityRank(Confidentiality) < OntologyWindowViewModel.ConfidentialityRank(minimum))
        {
            IsError = true;
            Status = $"Not saved: confidentiality must be at least {minimum} (level of the parents)";
            ActivityLog.Error("Ontology", $"Save of \"{DisplayName}\" refused: {Confidentiality} is below its parents' {minimum}");
            return;
        }

        // Raising a node also raises its less confidential descendants (after confirmation).
        var raised = OntologyWindowViewModel.ConfidentialityRank(Confidentiality)
                     > OntologyWindowViewModel.ConfidentialityRank(_entry.Confidentiality);
        var lowerDescendants = raised ? _owner.DescendantsBelow(this, Confidentiality) : [];
        if (lowerDescendants.Count > 0 && !await _owner.ConfirmRaiseDescendantsAsync(this, Confidentiality, lowerDescendants.Count))
        {
            Status = "Save cancelled";
            return;
        }

        var updated = ToEntry();
        var isNew = IsNew;
        IsError = false;
        Status = isNew ? "Creating…" : "Saving…";

        try
        {
            var result = isNew
                ? await _assistant.CreateOntologyAsync(updated, cancellationToken)
                : await _assistant.UpdateOntologyAsync(updated, cancellationToken);
            if (!result.IsSuccess)
            {
                IsError = true;
                Status = result.Message ?? "The Kaonomi server rejected the save.";
                ActivityLog.Error("Ontology", $"{(isNew ? "Create" : "Update")} \"{DisplayName}\" rejected: {Status}");
                return;
            }

            _entry = updated;
            IsNew = false;
            IsDirty = false;
            OnPropertyChanged(nameof(DatesLabel));
            Status = $"{(isNew ? "Created" : "Saved")} · {DateTime.Now:T}";
            ActivityLog.Info("Ontology", $"Node {(isNew ? "created" : "updated")}: \"{DisplayName}\" ({Id})");

            if (lowerDescendants.Count > 0)
                await _owner.RaiseDescendantsAsync(this, Confidentiality, lowerDescendants);
        }
        catch (OperationCanceledException)
        {
            Status = "Save cancelled";
            ActivityLog.Info("Ontology", $"Save of \"{DisplayName}\" cancelled");
        }
        catch (HttpRequestException ex) when (ex.StatusCode is null)
        {
            IsError = true;
            Status = $"Kaonomi server unreachable at {_assistant.BaseAddress} ({ex.Message})";
            ActivityLog.Error("Ontology", $"\"{DisplayName}\" not saved: server unreachable", ex);
        }
        catch (Exception ex)
        {
            IsError = true;
            Status = ex.Message;
            ActivityLog.Error("Ontology", $"\"{DisplayName}\" not saved", ex);
        }
    }

    /// <summary>Discards edits; a new node that was never saved is removed from the tree.</summary>
    [RelayCommand(CanExecute = nameof(CanSave))]
    private void Revert()
    {
        if (IsNew)
        {
            _owner.RemoveUnsavedNode(this);
            return;
        }

        Load(_entry);
        Status = "Changes discarded";
        ActivityLog.Info("Ontology", $"Changes discarded on \"{DisplayName}\"");
    }

    /// <summary>Saves only the soft-delete flag (keeps pending edits of other fields untouched).</summary>
    /// <summary>Saves only the virtual parents (pending edits of other fields are kept). Returns false when rejected.</summary>
    public async Task<bool> SetVirtualParentsAsync(List<string> virtualParentIds, CancellationToken cancellationToken = default)
    {
        var updated = _entry.Copy();
        updated.VirtualParentIds = virtualParentIds;

        var result = await _assistant.UpdateOntologyAsync(updated, cancellationToken);
        if (!result.IsSuccess)
        {
            IsError = true;
            Status = result.Message ?? "The Kaonomi server rejected the change.";
            return false;
        }

        _entry = updated;
        RefreshParentLabel();
        return true;
    }

    public async Task<bool> SetDeletedAsync(bool isDeleted, CancellationToken cancellationToken = default)
    {
        var updated = _entry.Copy();
        updated.IsDeleted = isDeleted;

        var result = await _assistant.UpdateOntologyAsync(updated, cancellationToken);
        if (!result.IsSuccess)
        {
            IsError = true;
            Status = result.Message ?? "The Kaonomi server rejected the change.";
            ActivityLog.Error("Ontology", $"isDeleted = {isDeleted} rejected for \"{DisplayName}\": {Status}");
            return false;
        }

        _entry = updated;
        IsDeleted = isDeleted;
        Status = isDeleted ? "Deleted" : "Restored";
        return true;
    }

    /// <summary>Reloads the node with <c>GET /ontology/{id}</c> unless it has local edits.</summary>
    public async Task RefreshFromServerAsync(CancellationToken cancellationToken = default)
    {
        if (IsNew || IsDirty)
            return;

        try
        {
            var fresh = await _assistant.GetOntologyAsync(Id, cancellationToken);
            if (fresh is null || IsDirty)
                return;

            // Keep the tree position stable: the parent is only changed by a full refresh.
            fresh.Id = Id;
            fresh.NodeParentId = _entry.NodeParentId;
            fresh.VirtualParentIds = _entry.VirtualParentIds;
            _entry = fresh;
            Load(fresh);
            OnPropertyChanged(nameof(DatesLabel));
        }
        catch (Exception ex) when (ex is HttpRequestException or TaskCanceledException or System.Text.Json.JsonException)
        {
            // The tree copy is still usable; report but do not block editing.
            Status = $"Could not refresh from server: {ex.Message}";
            ActivityLog.Error("Ontology", $"GET /ontology/{Id} failed for \"{DisplayName}\"", ex);
        }
    }

    private void Load(OntologyEntry entry)
    {
        _isLoading = true;
        try
        {
            AppName = entry.AppName ?? string.Empty;
            MachineName = entry.MachineName ?? string.Empty;
            UserName = entry.UserName ?? string.Empty;
            Comment = entry.Comment ?? string.Empty;
            Name = entry.Name ?? string.Empty;
            // The drop-down must already contain the stored value, otherwise it would clear it.
            _owner.EnsureEntityTypeOption(entry.EntityType?.Trim());
            EntityType = entry.EntityType?.Trim() ?? string.Empty;
            Description = entry.Description ?? string.Empty;
            Symbol = entry.Symbol ?? string.Empty;
            IsOntologyClass = entry.IsOntologyClass;
            SentencesExemples = JoinLines(entry.SentencesExemples);
            Synonyms = JoinLines(entry.Synonyms);
            Tags = JoinLines(entry.Tags);
            RelatedLinks = JoinLines(entry.RelatedLinks);
            RelatedEntities = JoinLines(entry.RelatedEntities);
            // Mapped to a drop-down value (unknown values are added to the drop-down so they are not erased).
            Confidentiality = _owner.ResolveConfidentiality(entry.Confidentiality);
            AngryLevel = entry.AngryLevel ?? 0;
            SadLevel = entry.SadLevel ?? 0;
            HappyLevel = entry.HappyLevel ?? 0;
            FearLevel = entry.FearLevel ?? 0;
            SurpriseLevel = entry.SurpriseLevel ?? 0;
            DisgustLevel = entry.DisgustLevel ?? 0;
            IsDeleted = entry.IsDeleted;
            IsDirty = IsNew;
            IsError = false;
        }
        finally
        {
            _isLoading = false;
        }
    }

    /// <summary>Copy of the values currently edited (also used as note context).</summary>
    internal OntologyEntry ToEntry()
    {
        var entry = _entry.Copy();
        entry.AppName = AppName;
        entry.MachineName = MachineName;
        entry.UserName = UserName;
        entry.Comment = Comment;
        entry.Name = Name;
        entry.EntityType = EntityType;
        entry.Description = Description;
        entry.Symbol = Symbol;
        entry.IsOntologyClass = IsOntologyClass;
        entry.SentencesExemples = SplitLines(SentencesExemples);
        entry.Synonyms = SplitLines(Synonyms);
        entry.Tags = SplitLines(Tags);
        entry.RelatedLinks = SplitLines(RelatedLinks);
        entry.RelatedEntities = SplitLines(RelatedEntities);
        entry.Confidentiality = Confidentiality;
        entry.AngryLevel = ToInt(AngryLevel);
        entry.SadLevel = ToInt(SadLevel);
        entry.HappyLevel = ToInt(HappyLevel);
        entry.FearLevel = ToInt(FearLevel);
        entry.SurpriseLevel = ToInt(SurpriseLevel);
        entry.DisgustLevel = ToInt(DisgustLevel);
        entry.IsDeleted = IsDeleted;
        return entry;
    }

    // A cleared box counts as 0, the default level.
    private static int? ToInt(decimal? value) => (int)Math.Round(value ?? 0);

    private static string JoinLines(List<string>? lines) => string.Join(Environment.NewLine, lines ?? []);

    private static List<string> SplitLines(string text) =>
        text.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).ToList();
}
