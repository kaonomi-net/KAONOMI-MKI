namespace KAONOMI.ImmuneSystem.Scanning;

/// <summary>The command line.</summary>
public sealed class Options
{
    public List<string> Roots { get; } = [];

    /// <summary>Every fixed drive (Windows, Linux) or the whole disk (macOS) instead of the home folder.</summary>
    public bool Machine { get; set; }

    public bool Images { get; set; } = true;
    public bool Office { get; set; } = true;

    /// <summary>Also the hidden folders, ~/Library, AppData, node_modules… (left out by default).</summary>
    public bool All { get; set; }

    /// <summary>The JSON file; <c>-</c> writes it on the standard output.</summary>
    public string? Out { get; set; }

    /// <summary>Office files larger than this are not opened (MB).</summary>
    public int MaxSizeMb { get; set; } = 200;

    public Confidence MinConfidence { get; set; } = Confidence.Low;

    /// <summary>Leaves the code itself out of the report (only what it does).</summary>
    public bool NoCode { get; set; }

    /// <summary>The code of one finding is cut after this many characters.</summary>
    public int MaxCode { get; set; } = 20_000;

    /// <summary>Looks for source code written as text in Word and PowerPoint documents.</summary>
    public bool CodeText { get; set; } = true;

    /// <summary>Reads the browser histories: the AI services used, the images and Office files downloaded.</summary>
    public bool History { get; set; } = true;

    /// <summary>The home folder whose browser profiles are read (default: the user's).</summary>
    public string? HistoryHome { get; set; }

    public bool Quiet { get; set; }

    /// <summary>Progress and findings as JSON lines on the error output, for a program that runs the scan (the chat's /immune).</summary>
    public bool Progress { get; set; }
    public int Threads { get; set; } = Math.Max(2, Environment.ProcessorCount);
    public bool Help { get; set; }

    public const string Usage = """
        KAONOMI.ImmuneSystem: looks on this machine for images generated by AI, and for code in Office files.

        Usage: KAONOMI.ImmuneSystem [folder…] [options]

          folder…              Folders to scan (default: your home folder)
          --machine            Scan the whole machine (every fixed drive; / on macOS and Linux)
          --images-only        Only the images generated by AI
          --office-only        Only the code in Office files
          --all                Also hidden folders, ~/Library, AppData, node_modules, .git…
          --out <file.json>    Where to write the report (default: immune-system-<date>.json; - = standard output)
          --min-confidence <low|medium|high>
                               Keep only the AI images at least this sure (default: low)
          --no-code            Do not copy the code into the report, only what it does
          --max-code <n>       Characters of code kept per finding (default: 20000)
          --no-code-text       Do not look for source code written as text in Word and PowerPoint
          --no-history         Do not read the browser histories (AI services used, files downloaded)
          --history-home <folder>
                               Read the browser profiles of this home folder (default: yours)
          --max-size <MB>      Office files larger than this are skipped (default: 200)
          --threads <n>        Files read at the same time (default: number of cores)
          --quiet              No progress on the console
          --progress           Progress and findings as JSON lines on the error output (for programs;
                               a line "cancel" on the standard input stops the scan and writes the report)
          -h, --help           This help

        Exit code: 0 nothing found, 1 something found, 2 bad command line.
        """;

    /// <summary>Reads the arguments; throws <see cref="ArgumentException"/> with a message for the user.</summary>
    public static Options Parse(string[] args)
    {
        var o = new Options();
        for (var i = 0; i < args.Length; i++)
        {
            var a = args[i];
            string Next() => i + 1 < args.Length ? args[++i] : throw new ArgumentException($"{a} needs a value");
            int NextInt()
            {
                var v = Next();
                return int.TryParse(v, out var n) && n > 0 ? n : throw new ArgumentException($"{a}: {v} is not a positive number");
            }

            switch (a)
            {
                case "-h" or "--help" or "/?": o.Help = true; break;
                case "--machine": o.Machine = true; break;
                case "--images-only": o.Office = false; o.Images = true; break;
                case "--office-only": o.Images = false; o.Office = true; break;
                case "--all": o.All = true; break;
                case "--out" or "-o": o.Out = Next(); break;
                case "--min-confidence":
                    var c = Next();
                    o.MinConfidence = Enum.TryParse<Confidence>(c, true, out var conf)
                        ? conf : throw new ArgumentException($"--min-confidence: {c} is not low, medium or high");
                    break;
                case "--no-code": o.NoCode = true; break;
                case "--max-code": o.MaxCode = NextInt(); break;
                case "--no-code-text": o.CodeText = false; break;
                case "--no-history": o.History = false; break;
                case "--history-home": o.HistoryHome = Next(); break;
                case "--max-size": o.MaxSizeMb = NextInt(); break;
                case "--threads": o.Threads = NextInt(); break;
                case "--quiet" or "-q": o.Quiet = true; break;
                case "--progress": o.Progress = true; break;
                default:
                    if (a.StartsWith('-'))
                        throw new ArgumentException($"Unknown option {a}");
                    o.Roots.Add(a);
                    break;
            }
        }
        return o;
    }

    /// <summary>The options as written in the report.</summary>
    public object ForReport() => new
    {
        Machine, Images, Office, All, MinConfidence = MinConfidence.ToString().ToLowerInvariant(),
        NoCode, MaxCode, CodeText, History, MaxSizeMb, Threads,
    };
}
